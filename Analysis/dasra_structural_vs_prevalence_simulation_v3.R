validate_config <- function(config) {
    if (!is.finite(config$n_rep) || config$n_rep < 1L) {
        stop("CONFIG$n_rep must be a positive integer.", call. = FALSE)
    }
    if (!is.finite(config$n_per_group) || config$n_per_group < 20L) {
        stop("CONFIG$n_per_group must be at least 20.", call. = FALSE)
    }
    if (!is.finite(config$alpha) || config$alpha <= 0 || config$alpha >= 1) {
        stop("CONFIG$alpha must lie strictly between 0 and 1.", call. = FALSE)
    }
    if (config$base_structural_absence <= 0 ||
        config$base_structural_absence >= 1) {
        stop("The baseline structural-absence probability must lie in (0, 1).",
             call. = FALSE)
    }
    if (!is.finite(config$structural_base_relative_abundance) ||
        config$structural_base_relative_abundance <= 0 ||
        config$structural_base_relative_abundance >= 1) {
        stop(
            "The structural-scenario baseline relative abundance must lie in (0, 1).",
            call. = FALSE
        )
    }
    if (!is.finite(config$detectability_base_relative_abundance) ||
        config$detectability_base_relative_abundance <= 0 ||
        config$detectability_base_relative_abundance >= 1) {
        stop(
            "The detectability-scenario baseline relative abundance must lie in (0, 1).",
            call. = FALSE
        )
    }
    if (!is.finite(config$beta_shape1) || config$beta_shape1 <= 0) {
        stop("The fixed first beta shape parameter must be positive.",
             call. = FALSE)
    }
    invisible(config)
}

check_packages <- function() {
    required <- c("ZINQ", "maaslin3", "logistf", "ggplot2", "dplyr")
    missing <- required[!vapply(required, requireNamespace, logical(1),
                               quietly = TRUE)]
    dasra_namespace <- if (requireNamespace("DASRA", quietly = TRUE)) {
        "DASRA"
    } else if (requireNamespace("dasra", quietly = TRUE)) {
        "dasra"
    } else {
        NA_character_
    }
    if (is.na(dasra_namespace)) {
        missing <- c(missing, "DASRA")
    }
    if (length(missing)) {
        stop(
            paste0(
                "Missing required package(s): ", paste(unique(missing), collapse = ", "),
                ".\nInstall ZINQ with remotes::install_github(\"wdl2459/ZINQ-v2\"), ",
                "MaAsLin 3 with BiocManager::install(\"maaslin3\"), and install ",
                "the local DASRA package before running this script."
            ),
            call. = FALSE
        )
    }
    fingerprint_names <- c(
        "dasra",
        "zt_fit_beta",
        "zt_fit_alpha",
        "zt_count_structural_test"
    )
    list(
        dasra_namespace = dasra_namespace,
        dasra = getExportedValue(dasra_namespace, "dasra"),
        dasra_fingerprint = function_fingerprint(
            dasra_namespace, fingerprint_names
        )
    )
}

collapse_conditions <- function(x) {
    x <- unique(trimws(x[nzchar(trimws(x))]))
    if (!length(x)) NA_character_ else paste(x, collapse = " | ")
}

text_md5 <- function(text) {
    path <- tempfile("dasra_sim_fingerprint_")
    on.exit(unlink(path), add = TRUE)
    writeLines(enc2utf8(as.character(text)), path, useBytes = TRUE)
    unname(tools::md5sum(path))
}

function_fingerprint <- function(namespace, function_names) {
    namespace_environment <- asNamespace(namespace)
    available <- function_names[vapply(
        function_names,
        exists,
        logical(1),
        envir = namespace_environment,
        inherits = FALSE
    )]
    if (!length(available)) {
        stop("No DASRA functions were available for fingerprinting.",
             call. = FALSE)
    }
    pieces <- vapply(available, function(name) {
        fun <- get(name, envir = namespace_environment, inherits = FALSE)
        paste(
            name,
            paste(deparse(formals(fun), width.cutoff = 500L), collapse = "\n"),
            paste(deparse(body(fun), width.cutoff = 500L), collapse = "\n"),
            sep = "\n"
        )
    }, character(1))
    text_md5(pieces)
}

