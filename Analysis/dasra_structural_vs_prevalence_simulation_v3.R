    saveRDS(object, path, version = 3)
    unname(tools::md5sum(path))
}

beta_shape2_from_mean <- function(mean_abundance, shape1) {
    mean_abundance <- as.numeric(mean_abundance)
    shape1 <- as.numeric(shape1)
    if (length(shape1) != 1L || !is.finite(shape1) || shape1 <= 0 ||
        any(!is.finite(mean_abundance)) ||
        any(mean_abundance <= 0 | mean_abundance >= 1)) {
        stop("Invalid beta-distribution parameters.", call. = FALSE)
    }
    shape1 * (1 - mean_abundance) / mean_abundance
}

beta_detection_probability <- function(N, mean_abundance, shape1) {
    N <- as.numeric(N)
    shape2 <- beta_shape2_from_mean(mean_abundance, shape1)
    log_p_zero <- lbeta(shape1, shape2 + N) - lbeta(shape1, shape2)
    p_detect <- -expm1(log_p_zero)
    pmin(pmax(p_detect, 0), 1)
}

expected_observed_prevalence <- function(N, rho, mean_abundance, shape1) {
    (1 - rho) * mean(beta_detection_probability(
        N = N,
        mean_abundance = mean_abundance,
        shape1 = shape1
    ))
}

solve_mean_for_prevalence <- function(N, rho, target_prevalence, shape1) {
    objective <- function(mean_abundance) {
        expected_observed_prevalence(
            N = N,
            rho = rho,
            mean_abundance = mean_abundance,
            shape1 = shape1
        ) - target_prevalence
    }
    lower <- 1e-8
    upper <- 0.02
    f_lower <- objective(lower)
    f_upper <- objective(upper)
    if (!is.finite(f_lower) || !is.finite(f_upper) ||
        f_lower > 0 || f_upper < 0) {
        stop(
            sprintf(
                paste0("Could not match observed prevalence: target=%.6f, ",
                       "rho=%.6f, lower residual=%.6g, upper residual=%.6g."),
                target_prevalence, rho, f_lower, f_upper
            ),
            call. = FALSE
        )
    }
    stats::uniroot(objective, interval = c(lower, upper),
                   tol = 1e-12)$root
}

make_target_specs <- function(N_reference, N_comparison, config) {
    rho0 <- config$base_structural_absence
    mu_structural0 <- config$structural_base_relative_abundance
    mu_detectability0 <- config$detectability_base_relative_abundance
    shape1 <- config$beta_shape1
    rows <- list()
    row_id <- 0L

    structural_baseline_prevalence <- expected_observed_prevalence(
        N_reference, rho0, mu_structural0, shape1
    )
    detectability_baseline_prevalence <- expected_observed_prevalence(
        N_reference, rho0, mu_detectability0, shape1
    )

    for (k in seq_along(config$structural_log_odds_effects)) {
        effect <- config$structural_log_odds_effects[k]
        rho1 <- stats::plogis(stats::qlogis(rho0) + effect)
        mu1 <- solve_mean_for_prevalence(
            N = N_comparison,
            rho = rho1,
            target_prevalence = structural_baseline_prevalence,
            shape1 = shape1
        )
        prev1 <- expected_observed_prevalence(
            N_comparison, rho1, mu1, shape1
        )
        row_id <- row_id + 1L
        rows[[row_id]] <- data.frame(
            target = sprintf("SA_masked_E%02d", k - 1L),
            scenario = "structural_masked",
            scenario_label = paste0(
                "Structural-absence difference\nwith matched observed prevalence"
            ),
            effect_index = k - 1L,
            effect_parameter = effect,
            effect_parameter_name = "structural log-odds shift",
            rho_reference = rho0,
            rho_comparison = rho1,
            mean_abundance_reference = mu_structural0,
            mean_abundance_comparison = mu1,
            expected_prevalence_reference = structural_baseline_prevalence,
            expected_prevalence_comparison = prev1,
            stringsAsFactors = FALSE
        )
    }

    for (k in seq_along(config$detectability_log_abundance_effects)) {
        effect <- config$detectability_log_abundance_effects[k]
        mu1 <- mu_detectability0 * exp(-effect)
        prev1 <- expected_observed_prevalence(
            N_comparison, rho0, mu1, shape1
        )
        row_id <- row_id + 1L
        rows[[row_id]] <- data.frame(
            target = sprintf("Detection_E%02d", k - 1L),
            scenario = "detectability_only",
            scenario_label = paste0(
                "Observed-prevalence difference\nwith no structural-absence difference"
            ),
            effect_index = k - 1L,
            effect_parameter = effect,
            effect_parameter_name = "log conditional-abundance decrease",
            rho_reference = rho0,
            rho_comparison = rho0,
            mean_abundance_reference = mu_detectability0,
            mean_abundance_comparison = mu1,
            expected_prevalence_reference = detectability_baseline_prevalence,
            expected_prevalence_comparison = prev1,
            stringsAsFactors = FALSE
        )
    }

    if (isTRUE(config$include_concordant_structural_scenario)) {
        for (k in seq_along(config$structural_log_odds_effects)) {
            effect <- config$structural_log_odds_effects[k]
            rho1 <- stats::plogis(stats::qlogis(rho0) + effect)
            prev1 <- expected_observed_prevalence(
                N_comparison, rho1, mu_structural0, shape1
            )
            row_id <- row_id + 1L
            rows[[row_id]] <- data.frame(
                target = sprintf("SA_concordant_E%02d", k - 1L),
                scenario = "structural_concordant",
                scenario_label = paste0(
                    "Structural-absence difference\nwith an observed-prevalence difference"
                ),
                effect_index = k - 1L,
                effect_parameter = effect,
                effect_parameter_name = "structural log-odds shift",
                rho_reference = rho0,
                rho_comparison = rho1,
                mean_abundance_reference = mu_structural0,
                mean_abundance_comparison = mu_structural0,
                expected_prevalence_reference = structural_baseline_prevalence,
                expected_prevalence_comparison = prev1,
                stringsAsFactors = FALSE
            )
        }
    }

    specs <- do.call(rbind, rows)
    rownames(specs) <- specs$target
    specs$structural_absence_difference <-
        specs$rho_comparison - specs$rho_reference
    specs$observed_prevalence_difference <-
        specs$expected_prevalence_comparison -
        specs$expected_prevalence_reference
    specs$beta_shape1 <- shape1
    specs$beta_shape2_reference <- beta_shape2_from_mean(
        specs$mean_abundance_reference, shape1
    )
    specs$beta_shape2_comparison <- beta_shape2_from_mean(
        specs$mean_abundance_comparison, shape1
    )
    specs$conditional_logit_sd_reference <- sqrt(
        trigamma(shape1) + trigamma(specs$beta_shape2_reference)
    )
    specs$conditional_logit_sd_comparison <- sqrt(
        trigamma(shape1) + trigamma(specs$beta_shape2_comparison)
    )
    specs
}

background_rank_weights <- function(n_taxa) {
    ranks <- seq_len(n_taxa)
    weights <- ranks^(-1.15)
    weights / sum(weights)
}

simulate_dataset <- function(rep_id, config) {
    set.seed(config$base_seed + as.integer(rep_id) * 100003L)
    n0 <- config$n_per_group
    n1 <- config$n_per_group
    n <- n0 + n1
    g <- c(rep(0L, n0), rep(1L, n1))

    depth_reference <- round(stats::rlnorm(
        n0,
        meanlog = log(config$depth_median),
        sdlog = config$depth_sdlog
    ))
    depth_reference <- pmin(
        pmax(depth_reference, config$depth_min), config$depth_max
    )
    depth_comparison <- sample(depth_reference, size = n1, replace = FALSE)
    depth <- as.integer(c(depth_reference, depth_comparison))

    sample_names <- sprintf("Sample_%03d", seq_len(n))
    metadata <- data.frame(
        group = factor(ifelse(g == 0L, "control", "case"),
                       levels = c("control", "case")),
        reads = depth,
        log_depth = as.numeric(scale(log(depth))),
        row.names = sample_names,
        stringsAsFactors = FALSE
    )

    specs <- make_target_specs(depth_reference, depth_comparison, config)
    target_names <- specs$target
    n_targets <- nrow(specs)
    target_probability <- matrix(
        0,
        nrow = n,
        ncol = n_targets,
        dimnames = list(sample_names, target_names)
    )
    latent_absent <- matrix(
        FALSE,
        nrow = n,
        ncol = n_targets,
        dimnames = list(sample_names, target_names)
    )

    for (j in seq_len(n_targets)) {
        rho <- ifelse(g == 0L, specs$rho_reference[j],
                      specs$rho_comparison[j])
        mean_abundance <- ifelse(
            g == 0L,
            specs$mean_abundance_reference[j],
            specs$mean_abundance_comparison[j]
        )
        absent <- stats::rbinom(n, size = 1L, prob = rho) == 1L
        present_probability <- stats::rbeta(
            n,
            shape1 = config$beta_shape1,
            shape2 = beta_shape2_from_mean(
                mean_abundance, config$beta_shape1
            )
        )
        present_probability[absent] <- 0
        target_probability[, j] <- present_probability
        latent_absent[, j] <- absent
    }

    target_total <- rowSums(target_probability)
    guarded <- target_total > config$target_probability_guard
    if (any(guarded)) {
        target_probability[guarded, ] <-
            target_probability[guarded, , drop = FALSE] *
            (config$target_probability_guard / target_total[guarded])
        target_total <- rowSums(target_probability)
    }

    n_background <- config$n_background_taxa
    background_names <- sprintf("Background_%02d", seq_len(n_background))
    background_base <- background_rank_weights(n_background)
    background_alpha <- pmax(
        config$background_dirichlet_concentration * background_base,
        0.02
    )

    feature_names <- c(target_names, background_names)
    full_counts <- matrix(
        0L,
        nrow = n,
        ncol = length(feature_names),
        dimnames = list(sample_names, feature_names)
    )

    for (i in seq_len(n)) {
        background_draw <- stats::rgamma(
            n_background,
            shape = background_alpha,
            rate = 1
        )
        background_draw <- background_draw / sum(background_draw)
        probabilities <- c(
            target_probability[i, ],
            (1 - target_total[i]) * background_draw
        )
        probabilities <- pmax(probabilities, 0)
        probabilities <- probabilities / sum(probabilities)
        full_counts[i, ] <- as.integer(stats::rmultinom(
            1L, size = depth[i], prob = probabilities
        )[, 1L])
    }

    target_counts <- full_counts[, target_names, drop = FALSE]
    truth <- specs
    truth$replicate <- rep_id
    truth$actual_structural_absence_reference <- vapply(
        seq_len(n_targets),
        function(j) mean(latent_absent[g == 0L, j]),
        numeric(1)
    )
    truth$actual_structural_absence_comparison <- vapply(
        seq_len(n_targets),
        function(j) mean(latent_absent[g == 1L, j]),
        numeric(1)
    )
    truth$actual_prevalence_reference <- vapply(
        seq_len(n_targets),
        function(j) mean(target_counts[g == 0L, j] > 0),
        numeric(1)
    )
    truth$actual_prevalence_comparison <- vapply(
        seq_len(n_targets),
        function(j) mean(target_counts[g == 1L, j] > 0),
        numeric(1)
    )
    truth$probability_guarded_samples <- sum(guarded)

    list(
        full_counts = full_counts,
        target_counts = target_counts,
        metadata = metadata,
        truth = truth,
        target_names = target_names
    )
}

empty_method_result <- function(target_names, method, status,
                                warning = NA_character_) {
    data.frame(
        target = target_names,
        method = method,
        p_value = NA_real_,
        statistic = NA_real_,
        coefficient = NA_real_,
        available = FALSE,
        status = status,
        warning = warning,
        abundance_induced_flag = NA,
        stringsAsFactors = FALSE
    )
}

run_dasra_structural <- function(sim, dasra_function) {
    target_names <- sim$target_names
    warning_text <- character()
    fit <- tryCatch(
        withCallingHandlers(
            dasra_function(
                counts = t(sim$target_counts),
                metadata = sim$metadata,
                formula = ~ group,
                group = "group",
                library_size = "reads",
                taxa_are_rows = TRUE,
                reference = "control",
                component = "structural_absence",
                full_output = FALSE
            ),
            warning = function(w) {
                warning_text <<- c(warning_text, conditionMessage(w))
                invokeRestart("muffleWarning")
            }
        ),
        error = function(e) e
    )
    if (inherits(fit, "error")) {
        return(empty_method_result(
            target_names,
            method = "DASRA structural absence",
            status = paste0("error: ", conditionMessage(fit))
        ))
    }

    result <- fit$results
    diagnostics <- fit$diagnostics
    result_index <- match(target_names, result$taxon)
    diagnostic_index <- match(target_names, diagnostics$taxon)
    formed <- as.logical(
        diagnostics$formed_structural_absence[diagnostic_index]
    )
    p_value <- as.numeric(result$p_structural_absence[result_index])
    statistic <- if ("z_structural_absence" %in% names(result)) {
        as.numeric(result$z_structural_absence[result_index])
    } else {
        rep(NA_real_, length(target_names))
    }
    reason <- as.character(
        diagnostics$reason_structural_absence[diagnostic_index]
    )
    available <- formed & is.finite(p_value) & p_value >= 0 & p_value <= 1
    p_value[!available] <- NA_real_
    statistic[!available] <- NA_real_
    reason[available] <- "ok"

    data.frame(
        target = target_names,
        method = "DASRA structural absence",
        p_value = p_value,
        statistic = statistic,
        coefficient = NA_real_,
        available = available,
        status = reason,
        warning = collapse_conditions(warning_text),
        abundance_induced_flag = NA,
        stringsAsFactors = FALSE
    )
}

run_zinq_prevalence <- function(sim, config, rep_id) {
    target_names <- sim$target_names
    rows <- vector("list", length(target_names))
    for (j in seq_along(target_names)) {
        target <- target_names[j]
        dat <- data.frame(
            Y = as.numeric(sim$target_counts[, target]),
            group = as.numeric(sim$metadata$group == "case"),
            log_depth = sim$metadata$log_depth
        )
        warning_text <- character()
        official <- tryCatch(
            withCallingHandlers(
                ZINQ::ZINQ_tests(
                    formula.logistic = Y ~ group + log_depth,
                    formula.quantile = Y ~ group + log_depth,
                    C = "group",
                    y_CorD = "D",
                    data = dat,
                    taus = config$zinq_quantile_tau,
                    seed = config$base_seed + rep_id * 1009L + j
                ),
                warning = function(w) {
                    warning_text <<- c(warning_text, conditionMessage(w))
                    invokeRestart("muffleWarning")
                }
            ),
            error = function(e) e
        )

        p_value <- NA_real_
        status <- "official_function_failed"
        if (!inherits(official, "error")) {
            p_candidate <- as.numeric(official$pvalue.logistic)[1L]
            if (is.finite(p_candidate) && p_candidate >= 0 && p_candidate <= 1) {
                p_value <- p_candidate
                status <- "ok"
            }
        }

        if (!is.finite(p_value)) {
            dat$detected <- as.integer(dat$Y > 0)
            fallback <- tryCatch(
                withCallingHandlers(
                    logistf::logistf(
                        detected ~ group + log_depth,
                        data = dat
                    ),
                    warning = function(w) {
                        warning_text <<- c(warning_text, conditionMessage(w))
                        invokeRestart("muffleWarning")
                    }
                ),
                error = function(e) e
            )
            if (!inherits(fallback, "error")) {
                p_names <- names(fallback$prob)
                p_position <- match("group", p_names)
                if (!is.finite(p_position)) p_position <- 2L
                p_candidate <- as.numeric(fallback$prob[p_position])
                if (is.finite(p_candidate) && p_candidate >= 0 &&
                    p_candidate <= 1) {
                    p_value <- p_candidate
                    status <- "official_firth_prevalence_fallback"
                }
            } else {
                status <- paste0("error: ", conditionMessage(fallback))
            }
        }

        rows[[j]] <- data.frame(
            target = target,
            method = "ZINQ Firth prevalence",
            p_value = p_value,
            statistic = NA_real_,
            coefficient = NA_real_,
            available = is.finite(p_value),
            status = status,
            warning = collapse_conditions(warning_text),
            abundance_induced_flag = NA,
            stringsAsFactors = FALSE
        )
    }
    do.call(rbind, rows)
}

extract_maaslin3_prevalence_results <- function(fit, target_names) {
    prevalence <- fit$fit_data_prevalence
    results <- if (is.data.frame(prevalence)) {
        prevalence
    } else {
        prevalence$results
    }
    if (is.null(results) || !is.data.frame(results)) {
        return(empty_method_result(
            target_names,
            method = "MaAsLin 3 prevalence",
            status = "prevalence_results_unavailable"
        ))
    }

    rows <- vector("list", length(target_names))
    for (j in seq_along(target_names)) {
        target <- target_names[j]
        candidates <- results[results$feature == target, , drop = FALSE]
        if ("metadata" %in% names(candidates)) {
            candidates <- candidates[candidates$metadata == "group", , drop = FALSE]
        }
        if (nrow(candidates) > 1L && "value" %in% names(candidates)) {
            preferred <- candidates$value == "case"
            if (any(preferred, na.rm = TRUE)) {
                candidates <- candidates[which(preferred)[1L], , drop = FALSE]
            }
        }
        if (nrow(candidates) > 1L && "name" %in% names(candidates)) {
            preferred <- candidates$name %in% c("groupcase", "group case")
            if (any(preferred, na.rm = TRUE)) {
                candidates <- candidates[which(preferred)[1L], , drop = FALSE]
            }
        }
        if (!nrow(candidates)) {
            rows[[j]] <- empty_method_result(
                target,
                method = "MaAsLin 3 prevalence",
                status = "target_prevalence_row_unavailable"
            )
            next
        }
        candidate <- candidates[1L, , drop = FALSE]
        p_value <- as.numeric(candidate$pval_individual)[1L]
        coefficient <- if ("coef" %in% names(candidate)) {
            as.numeric(candidate$coef)[1L]
        } else {
            NA_real_
        }
        error_text <- if ("error" %in% names(candidate)) {
            as.character(candidate$error)[1L]
        } else {
            NA_character_
        }
        if (identical(error_text, "NA") || is.na(error_text) ||
            !nzchar(trimws(error_text))) {
            error_text <- NA_character_
        }
        available <- is.finite(p_value) && p_value >= 0 && p_value <= 1
        rows[[j]] <- data.frame(
            target = target,
            method = "MaAsLin 3 prevalence",
            p_value = if (available) p_value else NA_real_,
            statistic = NA_real_,
            coefficient = if (available) coefficient else NA_real_,
            available = available,
            status = if (available) {
                "ok"
            } else if (is.na(error_text) || !nzchar(trimws(error_text))) {
                "nonfinite_p_value"
            } else {
                error_text
            },
            warning = error_text,
            abundance_induced_flag = if (is.na(error_text)) {
                FALSE
            } else {
                grepl("abundance|induced", error_text, ignore.case = TRUE)
            },
            stringsAsFactors = FALSE
        )
    }
    do.call(rbind, rows)
}

run_maaslin3_prevalence <- function(sim, config, rep_id) {
    target_names <- sim$target_names
    output_dir <- tempfile(sprintf("maaslin3_rep_%04d_", rep_id))
    on.exit({
        try(maaslin3::maaslin_log_reset(), silent = TRUE)
        unlink(output_dir, recursive = TRUE, force = TRUE)
    }, add = TRUE)

    try(maaslin3::maaslin_log_reset(), silent = TRUE)
    warning_text <- character()
    fit <- tryCatch(
        {
            invisible(capture.output(
                fit_value <- withCallingHandlers(
                    suppressMessages(maaslin3::maaslin3(
                        input_data = as.data.frame(sim$full_counts),
                        input_metadata = sim$metadata,
                        output = output_dir,
                        formula = "~ group + log_depth",
                        min_abundance = 0,
                        min_prevalence = 0,
                        max_prevalence = 1.01,
                        zero_threshold = 0,
                        min_variance = 0,
                        normalization = "TSS",
                        transform = "LOG",
                        correction = "BH",
                        standardize = TRUE,
                        median_comparison_abundance = TRUE,
                        median_comparison_prevalence = FALSE,
                        warn_prevalence = isTRUE(
                            config$maaslin3_keep_abundance_warning
                        ),
                        augment = TRUE,
                        evaluate_only = NULL,
                        plot_summary_plot = FALSE,
                        plot_associations = FALSE,
                        max_pngs = 1,
                        cores = 1,
                        save_models = FALSE,
                        save_plots_rds = FALSE,
                        verbosity = "ERROR"
                    )),
                    warning = function(w) {
                        warning_text <<- c(warning_text, conditionMessage(w))
                        invokeRestart("muffleWarning")
                    }
                )
            ))
            fit_value
        },
        error = function(e) e
    )

    if (inherits(fit, "error")) {
        return(empty_method_result(
            target_names,
            method = "MaAsLin 3 prevalence",
            status = paste0("error: ", conditionMessage(fit)),
            warning = collapse_conditions(warning_text)
        ))
    }

    out <- extract_maaslin3_prevalence_results(fit, target_names)
    global_warning <- collapse_conditions(warning_text)
    if (!is.na(global_warning)) {
        out$warning <- ifelse(
            is.na(out$warning),
            global_warning,
            paste(out$warning, global_warning, sep = " | ")
        )
    }
    out
}

analyze_one_replicate <- function(rep_id, config, dasra_function,
                                  checkpoint_dir, run_signature) {
    checkpoint_file <- file.path(
        checkpoint_dir, sprintf("replicate_%04d.rds", rep_id)
    )
    if (isTRUE(config$resume) && file.exists(checkpoint_file)) {
        existing <- tryCatch(readRDS(checkpoint_file), error = function(e) NULL)
        if (!is.null(existing) && isTRUE(existing$success) &&
            identical(existing$run_signature, run_signature)) {
            return(existing)
        }
    }

    result <- tryCatch({
        sim <- simulate_dataset(rep_id, config)
        method_results <- dplyr::bind_rows(
            run_dasra_structural(sim, dasra_function),
            run_zinq_prevalence(sim, config, rep_id),
            run_maaslin3_prevalence(sim, config, rep_id)
        )
        raw <- dplyr::left_join(
            method_results,
            sim$truth,
            by = "target"
        )
        raw$replicate <- rep_id
        raw$reject <- ifelse(
            raw$available,
            raw$p_value < config$alpha,
            NA
        )
        list(
            success = TRUE,
            replicate = rep_id,
            run_signature = run_signature,
            raw = raw,
            truth = sim$truth,
            error = NA_character_
        )
    }, error = function(e) {
        list(
            success = FALSE,
            replicate = rep_id,
            run_signature = run_signature,
            raw = NULL,
            truth = NULL,
            error = conditionMessage(e)
        )
    })

    temporary_file <- paste0(
        checkpoint_file, ".tmp_", Sys.getpid(), "_", sample.int(1e8, 1L)
    )
    saveRDS(result, temporary_file)
    if (!file.rename(temporary_file, checkpoint_file)) {
        unlink(temporary_file)
        stop("Could not write replicate checkpoint: ", checkpoint_file,
             call. = FALSE)
    }
    result
}

wilson_interval <- function(successes, total, confidence = 0.95) {
    if (!is.finite(total) || total <= 0) return(c(NA_real_, NA_real_))
    z <- stats::qnorm(1 - (1 - confidence) / 2)
    p <- successes / total
    denominator <- 1 + z^2 / total
    center <- (p + z^2 / (2 * total)) / denominator
    half_width <- z * sqrt(
        p * (1 - p) / total + z^2 / (4 * total^2)
    ) / denominator
    c(max(0, center - half_width), min(1, center + half_width))
}

summarize_results <- function(raw_results, truth_results, config) {
    method_order <- c(
        "DASRA structural absence",
        "ZINQ Firth prevalence",
        "MaAsLin 3 prevalence"
    )
    raw_results$method <- factor(raw_results$method, levels = method_order)

    summary <- raw_results |>
        dplyr::group_by(
            scenario, scenario_label, effect_index, effect_parameter,
            effect_parameter_name, target, method
        ) |>
        dplyr::summarise(
            n_total = dplyr::n(),
            n_available = sum(available, na.rm = TRUE),
            availability_rate = mean(available, na.rm = TRUE),
            n_reject = sum(reject %in% TRUE, na.rm = TRUE),
            conditional_rejection_rate = ifelse(
                n_available > 0,
                n_reject / n_available,
                NA_real_
            ),
            rejection_rate = n_reject / n_total,
            overall_rejection_fraction = rejection_rate,
            maaslin3_abundance_induced_flag_rate = ifelse(
                any(!is.na(abundance_induced_flag)),
                mean(abundance_induced_flag, na.rm = TRUE),
                NA_real_
            ),
            .groups = "drop"
        )

    intervals <- t(vapply(
        seq_len(nrow(summary)),
        function(i) wilson_interval(
            summary$n_reject[i], summary$n_total[i]
        ),
        numeric(2)
    ))
    summary$ci_lower <- intervals[, 1L]
    summary$ci_upper <- intervals[, 2L]

    conditional_intervals <- t(vapply(
        seq_len(nrow(summary)),
        function(i) wilson_interval(
            summary$n_reject[i], summary$n_available[i]
        ),
        numeric(2)
    ))
    summary$conditional_ci_lower <- conditional_intervals[, 1L]
    summary$conditional_ci_upper <- conditional_intervals[, 2L]

    truth_summary <- truth_results |>
        dplyr::group_by(
            scenario, scenario_label, effect_index, effect_parameter,
            effect_parameter_name, target
        ) |>
        dplyr::summarise(
            rho_reference = mean(rho_reference),
            rho_comparison = mean(rho_comparison),
            mean_abundance_reference = mean(mean_abundance_reference),
            mean_abundance_comparison = mean(mean_abundance_comparison),
            expected_prevalence_reference = mean(expected_prevalence_reference),
            expected_prevalence_comparison = mean(expected_prevalence_comparison),
            beta_shape1 = mean(beta_shape1),
            beta_shape2_reference = mean(beta_shape2_reference),
            beta_shape2_comparison = mean(beta_shape2_comparison),
            conditional_logit_sd_reference = mean(
                conditional_logit_sd_reference
            ),
            conditional_logit_sd_comparison = mean(
                conditional_logit_sd_comparison
            ),
            expected_structural_absence_difference = mean(
                structural_absence_difference
            ),
            expected_observed_prevalence_difference = mean(
                observed_prevalence_difference
            ),
            actual_structural_absence_reference = mean(
                actual_structural_absence_reference
            ),
            actual_structural_absence_comparison = mean(
                actual_structural_absence_comparison
            ),
            actual_prevalence_reference = mean(actual_prevalence_reference),
            actual_prevalence_comparison = mean(actual_prevalence_comparison),
            mean_probability_guarded_samples = mean(
                probability_guarded_samples
            ),
            .groups = "drop"
        )
    truth_summary$actual_structural_absence_difference <-
        truth_summary$actual_structural_absence_comparison -
        truth_summary$actual_structural_absence_reference
    truth_summary$actual_observed_prevalence_difference <-
        truth_summary$actual_prevalence_comparison -
        truth_summary$actual_prevalence_reference

    summary <- dplyr::left_join(
        summary,
        truth_summary,
        by = c(
            "scenario", "scenario_label", "effect_index", "effect_parameter",
            "effect_parameter_name", "target"
        )
    )
    list(raw = raw_results, summary = summary, truth = truth_summary)
}

