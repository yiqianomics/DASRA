#!/usr/bin/env Rscript

# ==============================================================================
# DASRA structural-absence simulation against observed-prevalence methods
# ==============================================================================
#
# Primary comparison:
#   1. A structural-absence difference with matched expected observed prevalence.
#   2. An abundance-induced observed-prevalence difference with no structural-
#      absence difference.
#
# Conditional on ecological presence, the target taxon follows a beta
# distribution with a fixed first shape parameter. Its mean changes across
# groups while its logit-scale dispersion remains approximately stable. Read
# counts are then generated by multinomial sampling. This beta-multinomial
# mechanism differs from DASRA's logistic-normal working model without
# introducing an unintended group difference in conditional-present dispersion.
#
# All methods are evaluated with raw, unadjusted p-values at ALPHA. Because the
# methods target different null hypotheses, the output uses the neutral term
# "empirical rejection rate" rather than calling every curve power.
#
# Direct run:
#   Rscript dasra_structural_vs_prevalence_simulation_v2.R
#
# Optional environment variables:
#   DASRA_SIM_REPS=200
#   DASRA_SIM_N_PER_GROUP=200
#   DASRA_SIM_CORES=8
#   DASRA_SIM_OUTDIR=/path/to/output
#   DASRA_SIM_RESUME=true
#
# Required packages:
#   DASRA, ZINQ, maaslin3, logistf, ggplot2, dplyr
#
# Installation examples:
#   remotes::install_github("wdl2459/ZINQ-v2")
#   BiocManager::install("maaslin3")
#
# ==============================================================================

