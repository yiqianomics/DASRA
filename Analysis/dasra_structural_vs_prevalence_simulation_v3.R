main <- function() {
    validate_config(CONFIG)
    if (.Platform$OS.type == "windows" && CONFIG$n_cores > 1L) {
        stop(
            "This script uses parallel::mclapply and is configured for macOS/Linux. ",
            "Set DASRA_SIM_CORES=1 on Windows.",
            call. = FALSE
        )
    }
    package_info <- check_packages()

    output_dir <- normalizePath(
        CONFIG$output_dir,
        winslash = "/",
        mustWork = FALSE
    )
    checkpoint_dir <- file.path(output_dir, "replicate_checkpoints")
    dir.create(checkpoint_dir, recursive = TRUE, showWarnings = FALSE)

    design_config <- CONFIG
    design_config$n_rep <- NULL
    design_config$n_cores <- NULL
    design_config$output_dir <- NULL
    design_config$resume <- NULL
    software_versions <- vapply(
        c(package_info$dasra_namespace, "ZINQ", "maaslin3", "logistf"),
        function(pkg) as.character(utils::packageVersion(pkg)),
        character(1)
    )
    design_record <- list(
        design = design_config,
        software_versions = software_versions,
        software_fingerprints = c(
            DASRA = package_info$dasra_fingerprint
        ),
        runtime = c(
            R = R.version.string,
            platform = R.version$platform
        )
    )
    run_signature <- object_fingerprint(design_record)
    config_file <- file.path(output_dir, "simulation_design_config.rds")
    if (file.exists(config_file)) {
        previous <- readRDS(config_file)
        if (!identical(previous, design_record)) {
            stop(
                "The output directory contains checkpoints from a different design or software version. ",
                "Choose a new DASRA_SIM_OUTDIR.",
                call. = FALSE
            )
        }
    } else {
        saveRDS(design_record, config_file)
    }

    write_method_settings(CONFIG, package_info, output_dir)
    write_session_information(CONFIG, package_info, output_dir)

    message(sprintf(
        "Running %d replicate(s) with %d parallel worker(s).",
        CONFIG$n_rep, CONFIG$n_cores
    ))
    replicate_ids <- seq_len(CONFIG$n_rep)
    worker <- function(rep_id) {
        analyze_one_replicate(
            rep_id = rep_id,
            config = CONFIG,
            dasra_function = package_info$dasra,
            checkpoint_dir = checkpoint_dir,
            run_signature = run_signature
        )
    }
    replicate_results <- if (CONFIG$n_cores == 1L) {
        lapply(replicate_ids, worker)
    } else {
        parallel::mclapply(
            replicate_ids,
            worker,
            mc.cores = CONFIG$n_cores,
            mc.preschedule = TRUE,
            mc.set.seed = FALSE
        )
    }

    success <- vapply(replicate_results, function(x) isTRUE(x$success),
                      logical(1))
    if (any(!success)) {
        errors <- data.frame(
            replicate = vapply(
                replicate_results[!success], `[[`, integer(1), "replicate"
            ),
            error = vapply(
                replicate_results[!success], `[[`, character(1), "error"
            ),
            stringsAsFactors = FALSE
        )
        utils::write.csv(
            errors,
            file.path(output_dir, "replicate_errors.csv"),
            row.names = FALSE
        )
        warning(sprintf(
            "%d replicate(s) failed. Details are in replicate_errors.csv.",
            sum(!success)
        ), call. = FALSE)
    }
    successful_results <- replicate_results[success]
    if (!length(successful_results)) {
        stop("No simulation replicate completed successfully.", call. = FALSE)
    }

    raw_results <- dplyr::bind_rows(lapply(successful_results, `[[`, "raw"))
    truth_results <- dplyr::bind_rows(lapply(successful_results, `[[`, "truth"))
    summaries <- summarize_results(raw_results, truth_results, CONFIG)

    utils::write.csv(
        summaries$raw,
        file.path(output_dir, "combined_raw_results.csv"),
        row.names = FALSE
    )
    utils::write.csv(
        summaries$summary,
        file.path(output_dir, "combined_rejection_summary.csv"),
        row.names = FALSE
    )
    utils::write.csv(
        summaries$truth,
        file.path(output_dir, "combined_truth_summary.csv"),
        row.names = FALSE
    )
    utils::write.csv(
        truth_results,
        file.path(output_dir, "combined_truth_by_replicate.csv"),
        row.names = FALSE
    )

    failure_summary <- summaries$raw |>
        dplyr::filter(!available) |>
        dplyr::count(method, scenario, status, name = "n") |>
        dplyr::arrange(method, scenario, dplyr::desc(n))
    utils::write.csv(
        failure_summary,
        file.path(output_dir, "method_failure_summary.csv"),
        row.names = FALSE
    )

    warning_summary <- summaries$raw |>
        dplyr::filter(!is.na(warning), nzchar(trimws(warning))) |>
        dplyr::count(method, scenario, warning, name = "n") |>
        dplyr::arrange(method, scenario, dplyr::desc(n))
    utils::write.csv(
        warning_summary,
        file.path(output_dir, "method_warning_summary.csv"),
        row.names = FALSE
    )

    plot_rejection_scenario(
        summaries$summary,
        scenario = "structural_masked",
        x_variable = "expected_structural_absence_difference",
        x_label = "Difference in structural-absence probability",
        output_stem = "fig_structural_absence_signal",
        output_dir = output_dir,
        alpha = CONFIG$alpha
    )
    plot_rejection_scenario(
        summaries$summary,
        scenario = "detectability_only",
        x_variable = "expected_observed_prevalence_difference",
        x_label = "Absolute expected observed-prevalence difference",
        output_stem = "fig_observed_prevalence_signal",
        output_dir = output_dir,
        alpha = CONFIG$alpha
    )
    if ("structural_concordant" %in% summaries$summary$scenario) {
        plot_rejection_scenario(
            summaries$summary,
            scenario = "structural_concordant",
            x_variable = "expected_structural_absence_difference",
            x_label = "Difference in structural-absence probability",
            output_stem = "fig_concordant_structural_signal",
            output_dir = output_dir,
            alpha = CONFIG$alpha
        )
    }
    plot_combined_rejection(
        summaries$summary, output_dir, alpha = CONFIG$alpha
    )
    plot_availability(summaries$summary, output_dir)
    plot_design_verification(summaries$truth, output_dir)

    message("Simulation complete.")
    message("Output directory: ", output_dir)
    print(summaries$summary[, c(
        "scenario", "effect_index", "method", "n_available",
        "availability_rate", "rejection_rate",
        "conditional_rejection_rate", "ci_lower", "ci_upper"
    )])
    invisible(summaries)
}

main()
