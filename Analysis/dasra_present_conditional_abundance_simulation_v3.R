#!/usr/bin/env Rscript

# =============================================================================
# DASRA present-conditional abundance simulation
# =============================================================================
#
# This standalone script implements a prototype of the proposed DASRA
# abundance component and compares it with:
#
#   1. the quantile-regression abundance component of ZINQ v2; and
#   2. the abundance component of MaAsLin 3.
#
# The proposed method uses the same latent structural-absence/count model as
# the DASRA structural component. It does not replace zeros with pseudocounts.
# Zero-count samples contribute to the abundance estimating equation through
# their posterior probability of ecological presence and their posterior
# latent-abundance score.
#
# The raw taxon-specific effect is a covariate-standardized difference in
# present-conditional mean log relative abundance. A target-excluded robust
# cross-taxon reference correction is then used to remove a shared
# compositional background, and sample-aligned influence contributions are
# used to propagate both taxon-specific and background-estimation uncertainty.
#
# Simulation strategy
# -------------------
# Counts are generated by a zero-inflated, correlated lognormal absolute-
# abundance model followed by multinomial sequencing. This is a common
# microbiome simulation strategy and deliberately differs from the
# taxon-specific logistic-normal working marginal used by the proposed method.
#
# Scenarios include:
#   * a global null;
#   * a sequencing-depth-imbalanced null;
#   * balanced present-conditional abundance signals;
#   * rare but ecologically widespread taxa with frequent finite-depth
#     nondetection;
#   * sparse and dense unidirectional abundance perturbations that stress
#     compositional correction;
#   * structural-absence differences with no direct abundance effects; and
#   * mixed structural-absence and abundance signals.
#
# Primary truth
# -------------
# A taxon is an abundance signal when its latent absolute abundance receives a
# direct group effect. This is the taxon-specific truth relevant to the
# compositionally centered DASRA and MaAsLin 3 median-comparison procedures.
# ZINQ's detected-sample quantile component targets a different, uncentered
# relative-abundance null; the script therefore also writes oracle latent-
# relative and detected-sample effect summaries so that estimand differences
# remain visible.
#
# Direct run
# ----------
#   Rscript dasra_present_conditional_abundance_simulation.R
#
# Recommended pilot
# -----------------
#   DASRA_ABUND_REPS=5 DASRA_ABUND_CORES=2 \
#     Rscript dasra_present_conditional_abundance_simulation.R
#
# Main run
# --------
#   DASRA_ABUND_REPS=100 DASRA_ABUND_CORES=8 \
#     Rscript dasra_present_conditional_abundance_simulation.R
#
# Optional environment variables
# ------------------------------
#   DASRA_ABUND_REPS=30
#   DASRA_ABUND_N_PER_GROUP=100
#   DASRA_ABUND_TAXA=30
#   DASRA_ABUND_CORES=8
#   DASRA_ABUND_OUTDIR=/path/to/output
#   DASRA_ABUND_RESUME=true
#   DASRA_ABUND_HEAVY_TAIL=false
#   DASRA_ABUND_Q=41
#
# Required packages
# -----------------
#   ZINQ, maaslin3, nleqslv, statmod, ggplot2, dplyr, tidyr
#
# Installation examples
# ---------------------
#   remotes::install_github("wdl2459/ZINQ-v2")
#   BiocManager::install("maaslin3")
#   install.packages(c("nleqslv", "statmod", "ggplot2", "dplyr", "tidyr"))
#
# =============================================================================

