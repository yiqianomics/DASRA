}

make_plots <- function(summary, raw, output_dir, alpha) {
    scenario_order <- SCENARIOS$scenario
    scenario_labels <- setNames(SCENARIOS$label, SCENARIOS$scenario)

    plot_summary <- summary %>%
        mutate(
            scenario_label = factor(
                scenario_labels[scenario],
                levels = scenario_labels[scenario_order]
            )
        )

    fdr_plot <- ggplot(
        plot_summary,
        aes(
            x = scenario_label,
            y = empirical_fdr,
            group = method,
            linetype = method,
            shape = method
        )
    ) +
        geom_hline(yintercept = alpha, linetype = 3) +
        geom_errorbar(
            aes(ymin = fdr_lower, ymax = fdr_upper),
            width = 0.10,
            position = position_dodge(width = 0.22)
        ) +
        geom_line(position = position_dodge(width = 0.22)) +
        geom_point(size = 2.3, position = position_dodge(width = 0.22)) +
        facet_wrap(~ dgp) +
        labs(
            x = NULL,
            y = "FDR relative to directly perturbed taxa",
            linetype = NULL,
            shape = NULL
        ) +
        publication_theme()
    save_publication_plot(
        fdr_plot, "fig_abundance_fdr", output_dir, 11, 6
    )

    type1_plot <- ggplot(
        plot_summary,
        aes(
            x = scenario_label,
            y = raw_type1,
            group = method,
            linetype = method,
            shape = method
        )
    ) +
        geom_hline(yintercept = alpha, linetype = 3) +
        geom_line(position = position_dodge(width = 0.22)) +
        geom_point(size = 2.3, position = position_dodge(width = 0.22)) +
        facet_wrap(~ dgp) +
        labs(
            x = NULL,
            y = "Rejection rate among non-perturbed taxa",
            linetype = NULL,
            shape = NULL
        ) +
        publication_theme()
    save_publication_plot(
        type1_plot, "fig_abundance_type1", output_dir, 11, 6
    )

    power_data <- plot_summary %>% filter(is.finite(power))
    power_plot <- ggplot(
        power_data,
        aes(
            x = scenario_label,
            y = power,
            group = method,
            linetype = method,
            shape = method
        )
    ) +
        geom_errorbar(
            aes(ymin = power_lower, ymax = power_upper),
            width = 0.10,
            position = position_dodge(width = 0.22)
        ) +
        geom_line(position = position_dodge(width = 0.22)) +
        geom_point(size = 2.3, position = position_dodge(width = 0.22)) +
        facet_wrap(~ dgp) +
        coord_cartesian(ylim = c(0, 1)) +
        labs(
            x = NULL,
            y = "Abundance power",
            linetype = NULL,
            shape = NULL
        ) +
        publication_theme()
    save_publication_plot(
        power_plot, "fig_abundance_power", output_dir, 11, 6
    )

    availability_plot <- ggplot(
        plot_summary,
        aes(
            x = scenario_label,
            y = availability,
            group = method,
            linetype = method,
            shape = method
        )
    ) +
        geom_line(position = position_dodge(width = 0.22)) +
        geom_point(size = 2.3, position = position_dodge(width = 0.22)) +
        facet_wrap(~ dgp) +
        coord_cartesian(ylim = c(0, 1)) +
        labs(
            x = NULL,
            y = "Proportion of abundance tests available",
            linetype = NULL,
            shape = NULL
        ) +
        publication_theme()
    save_publication_plot(
        availability_plot, "fig_abundance_availability", output_dir, 11, 6
    )

    qq_data <- raw %>%
        filter(
            scenario == "global_null",
            available,
            is.finite(p_value)
        ) %>%
        group_by(dgp, method) %>%
        arrange(p_value, .by_group = TRUE) %>%
        mutate(expected = (row_number() - 0.5) / n()) %>%
        ungroup()

    qq_plot <- ggplot(
        qq_data,
        aes(x = expected, y = p_value)
    ) +
        geom_abline(intercept = 0, slope = 1, linetype = 3) +
        geom_point(alpha = 0.35, size = 0.7) +
        facet_grid(dgp ~ method) +
        coord_equal(xlim = c(0, 1), ylim = c(0, 1)) +
        labs(
            x = "Expected uniform quantile",
            y = "Observed abundance p-value"
        ) +
        theme_classic(base_size = 11)
    save_publication_plot(
        qq_plot, "fig_abundance_global_null_qq", output_dir, 11, 6
    )
}

write_method_settings <- function(output_dir) {
    settings <- data.frame(
        method = c(
            "DASRA proposed abundance",
            "ZINQ quantile abundance",
            "MaAsLin 3 abundance"
        ),
        implementation = c(
            paste0(
                "Stacked positive-mark, structural-nuisance and posterior ",
                "abundance estimating equations; mean-log-relative effect; ",
                "target-excluded robust reference correction; joint influence variance"
            ),
            paste0(
                "ZINQ::ZINQ_tests quantile component on TSS relative ",
                "abundances; taus = ",
                paste(CONFIG$zinq_taus, collapse = ", "),
                "; quantile p-values combined by a Cauchy test"
            ),
            paste0(
                "maaslin3::maaslin3 abundance model; TSS, LOG, ",
                "standardize = TRUE, median_comparison_abundance = ",
                CONFIG$maaslin3_median_comparison,
                ", evaluate_only = abundance when supported"
            )
        ),
        zero_handling = c(
            "Zeros enter the finite-depth count likelihood",
            "Abundance quantiles use detected observations",
            "Linear abundance model uses detected observations"
        ),
        multiplicity = "BH recomputed over the common retained-taxon family",
        stringsAsFactors = FALSE
    )
    write.csv(
        settings,
        file.path(output_dir, "method_settings.csv"),
        row.names = FALSE
    )
}

# =============================================================================
# Main
# =============================================================================

main <- function() {
    if (.Platform$OS.type == "windows" && CONFIG$n_cores > 1L) {
        stop(
            "This script uses parallel::mclapply on macOS/Linux. ",
            "Set DASRA_ABUND_CORES=1 on Windows.",
            call. = FALSE
        )
    }

    software_versions <- vapply(required_packages, function(package) {
        as.character(utils::packageVersion(package))
    }, character(1))

    design_config <- CONFIG
    design_config$n_rep <- NULL
    design_config$n_cores <- NULL
    design_config$output_dir <- NULL
    design_config$resume <- NULL

    design_record <- list(
        design = design_config,
        scenarios = SCENARIOS,
        dgp_variants = DGP_VARIANTS,
        software_versions = software_versions,
        script_fingerprint = script_fingerprint(),
        R = R.version.string,
        platform = R.version$platform
    )
    run_signature <- object_fingerprint(design_record)

    design_path <- file.path(
        CONFIG$output_dir, "simulation_design_config.rds"
    )
    if (file.exists(design_path)) {
        previous <- readRDS(design_path)
        if (!identical(previous, design_record)) {
            stop(
                "The output directory contains checkpoints from a different ",
                "design, software environment or script version. Choose a ",
                "new DASRA_ABUND_OUTDIR.",
                call. = FALSE
            )
        }
    } else {
        saveRDS(design_record, design_path)
    }

    write_method_settings(CONFIG$output_dir)

    message("DASRA present-conditional abundance simulation")
    message("  Replications: ", CONFIG$n_rep)
    message("  Samples per group: ", CONFIG$n_per_group)
    message("  Taxa: ", CONFIG$n_taxa)
    message("  DGP variants: ", paste(DGP_VARIANTS, collapse = ", "))
    message("  Scenarios: ", paste(SCENARIOS$scenario, collapse = ", "))
    message("  Workers: ", CONFIG$n_cores)
    message("  Quadrature order: ", CONFIG$quadrature_order)
    message("  Output: ", normalizePath(
        CONFIG$output_dir, winslash = "/", mustWork = FALSE
    ))

    replicate_ids <- seq_len(CONFIG$n_rep)
    if (.Platform$OS.type == "unix" && CONFIG$n_cores > 1L) {
        replicate_results <- parallel::mclapply(
            replicate_ids,
            run_replicate,
            config = CONFIG,
            run_signature = run_signature,
            mc.cores = CONFIG$n_cores,
            mc.preschedule = FALSE,
            mc.set.seed = FALSE
        )
    } else {
        replicate_results <- lapply(
            replicate_ids,
            run_replicate,
            config = CONFIG,
            run_signature = run_signature
        )
    }

    successful <- vapply(
        replicate_results, function(x) isTRUE(x$success), logical(1)
    )
    if (!all(successful)) {
        failures <- data.frame(
            replicate = replicate_ids[!successful],
            error = vapply(
                replicate_results[!successful],
                function(x) x$error %||% "unknown error",
                character(1)
            )
        )
        write.csv(
            failures,
            file.path(CONFIG$output_dir, "replicate_failures.csv"),
            row.names = FALSE
        )
        warning(sum(!successful), " replicate(s) failed.")
    }
    if (!any(successful)) {
        stop("No replicate completed successfully.", call. = FALSE)
    }

    replicate_results <- replicate_results[successful]
    raw <- dplyr::bind_rows(lapply(replicate_results, `[[`, "raw"))
    metrics <- dplyr::bind_rows(lapply(replicate_results, `[[`, "metrics"))
    truth <- dplyr::bind_rows(lapply(replicate_results, `[[`, "truth"))
    summary <- summarize_metrics(metrics)

    write.csv(
        raw,
        file.path(CONFIG$output_dir, "combined_taxon_method_results.csv"),
        row.names = FALSE
    )
    write.csv(
        metrics,
        file.path(CONFIG$output_dir, "combined_replicate_metrics.csv"),
        row.names = FALSE
    )
    write.csv(
        summary,
        file.path(CONFIG$output_dir, "combined_power_type1_fdr_summary.csv"),
        row.names = FALSE
    )
    write.csv(
        truth,
        file.path(CONFIG$output_dir, "combined_simulation_truth.csv"),
        row.names = FALSE
    )
    write.csv(
        SCENARIOS,
        file.path(CONFIG$output_dir, "simulation_scenarios.csv"),
        row.names = FALSE
    )

    truth_summary <- truth %>%
        group_by(dgp, scenario, abundance_alt) %>%
        summarise(
            n_taxon_replications = n(),
            mean_baseline_relative_abundance =
                mean(baseline_relative_abundance),
            mean_positive_reference = mean(n_positive_reference),
            mean_positive_comparison = mean(n_positive_comparison),
            mean_present_nondetection_reference =
                safe_mean(present_nondetection_reference),
            mean_present_nondetection_comparison =
                safe_mean(present_nondetection_comparison),
            mean_oracle_latent_effect =
                safe_mean(oracle_latent_log_relative_effect),
            mean_oracle_detected_effect =
                safe_mean(oracle_detected_log_relative_effect),
            .groups = "drop"
        )
    write.csv(
        truth_summary,
        file.path(CONFIG$output_dir, "simulation_truth_summary.csv"),
        row.names = FALSE
    )

    status_summary <- raw %>%
        count(dgp, scenario, method, available, status, name = "n")
    write.csv(
        status_summary,
        file.path(CONFIG$output_dir, "method_status_summary.csv"),
        row.names = FALSE
    )

    make_plots(
        summary = summary,
        raw = raw,
        output_dir = CONFIG$output_dir,
        alpha = CONFIG$alpha
    )

    session_lines <- c(
        "DASRA present-conditional abundance simulation",
        paste0("Run date: ", format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")),
        "",
        "Configuration:",
        capture.output(str(CONFIG)),
        "",
        "Scenarios:",
        capture.output(print(SCENARIOS)),
        "",
        "Package versions:",
        paste0(names(software_versions), ": ", software_versions),
        "",
        "Script fingerprint:",
        as.character(design_record$script_fingerprint),
        "",
        "Session information:",
        capture.output(sessionInfo())
    )
    writeLines(
        session_lines,
        file.path(CONFIG$output_dir, "session_information.txt")
    )

    message("Simulation complete.")
    message("Key outputs:")
    message("  combined_power_type1_fdr_summary.csv")
    message("  combined_replicate_metrics.csv")
    message("  combined_taxon_method_results.csv")
    message("  combined_simulation_truth.csv")
    message("  simulation_truth_summary.csv")
    message("  method_status_summary.csv")
    message("  fig_abundance_fdr.pdf")
    message("  fig_abundance_type1.pdf")
    message("  fig_abundance_power.pdf")
    message("  fig_abundance_availability.pdf")
    message("  fig_abundance_global_null_qq.pdf")
}

main()
