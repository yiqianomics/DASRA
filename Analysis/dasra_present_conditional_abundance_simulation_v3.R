matched_group_vector <- function(values) {
    c(values, sample(values, length(values), replace = FALSE))
}

make_base_replication <- function(rep_id, dgp, config) {
    set.seed(
        config$base_seed + 10000L * rep_id +
            if (identical(dgp, "heavy_tail")) 700000L else 0L
    )

    n0 <- config$n_per_group
    n <- 2L * n0
    p <- config$n_taxa
    group <- c(rep(0, n0), rep(1, n0))

    # A measured covariate is moderately associated with group and affects both
    # structural absence and positive abundance.
    z <- config$covariate_group_shift * group + rnorm(n)

    # Depth is generated from the same empirical distribution in both groups.
    depth_reference <- round(exp(
        rnorm(n0, log(config$depth_median), config$depth_sdlog)
    ))
    depth_reference <- as.integer(clamp(
        depth_reference, config$depth_min, config$depth_max
    ))
    depth <- matched_group_vector(depth_reference)

    # Baseline absolute abundances span common to rare taxa.
    base_weight <- exp(seq(log(0.12), log(0.00035), length.out = p))
    base_weight <- base_weight / sum(base_weight)
    abundance_intercept <- log(base_weight)

    rho_intercept <- seq(qlogis(0.07), qlogis(0.38), length.out = p) +
        rnorm(p, 0, 0.10)
    rho_z_effect <- rnorm(p, 0, 0.12)
    abundance_z_effect <- rnorm(p, 0, 0.10)
    factor_loading <- rnorm(p, 0, config$loading_sd)
    abundance_sd <- runif(
        p, config$abundance_sd_min, config$abundance_sd_max
    )

    sample_factor <- rnorm(n, 0, config$sample_factor_sd)
    structural_uniform <- matrix(runif(n * p), nrow = n, ncol = p)
    if (identical(dgp, "heavy_tail")) {
        abundance_error <- matrix(
            rt(n * p, df = 4) / sqrt(2),
            nrow = n, ncol = p
        )
    } else {
        abundance_error <- matrix(rnorm(n * p), nrow = n, ncol = p)
    }

    taxa <- sprintf("Taxon_%03d", seq_len(p))
    samples <- sprintf("Sample_%03d", seq_len(n))

    list(
        group = group,
        z = z,
        depth = depth,
        abundance_intercept = abundance_intercept,
        rho_intercept = rho_intercept,
        rho_z_effect = rho_z_effect,
        abundance_z_effect = abundance_z_effect,
        factor_loading = factor_loading,
        abundance_sd = abundance_sd,
        sample_factor = sample_factor,
        structural_uniform = structural_uniform,
        abundance_error = abundance_error,
        taxa = taxa,
        samples = samples
    )
}

scenario_signal_vectors <- function(base, scenario, config) {
    p <- config$n_taxa
    abundance_effect <- numeric(p)
    structural_effect <- numeric(p)
    baseline_log_offset <- numeric(p)
    structural_log_odds_offset <- numeric(p)

    order_common_to_rare <- order(base$abundance_intercept, decreasing = TRUE)
    moderate <- order_common_to_rare[
        seq.int(4L, min(p - 6L, 15L))
    ]
    if (length(moderate) < 8L) moderate <- order_common_to_rare

    balanced_set <- moderate[seq_len(min(6L, length(moderate)))]
    if (length(balanced_set) %% 2L == 1L) {
        balanced_set <- balanced_set[-length(balanced_set)]
    }
    balanced_direction <- rep(c(1, -1), length.out = length(balanced_set))

    rare_set <- tail(order_common_to_rare, min(6L, p))
    if (length(rare_set) %% 2L == 1L) rare_set <- rare_set[-1L]
    rare_direction <- rep(c(1, -1), length.out = length(rare_set))

    sparse_set <- unique(round(seq(3, p - 3, length.out = min(4L, p - 4L))))
    dense_set <- order_common_to_rare[
        seq_len(max(4L, min(p - 4L, as.integer(round(0.40 * p)))))
    ]
    structural_candidates <- setdiff(
        order_common_to_rare,
        union(balanced_set, rare_set)
    )
    if (length(structural_candidates) < 4L) {
        structural_candidates <- order_common_to_rare
    }
    structural_set <- structural_candidates[seq_len(min(4L, p))]
    structural_direction <- rep(c(1, -1), length.out = length(structural_set))

    if (scenario == "balanced_abundance") {
        abundance_effect[balanced_set] <-
            config$balanced_abundance_effect * balanced_direction
    } else if (scenario == "rare_present_abundance") {
        abundance_effect[rare_set] <-
            config$rare_abundance_effect * rare_direction
        baseline_log_offset[rare_set] <-
            log(config$rare_baseline_multiplier)
        structural_log_odds_offset[rare_set] <-
            config$rare_structural_log_odds_offset
    } else if (scenario == "sparse_unidirectional") {
        abundance_effect[sparse_set] <-
            config$sparse_unidirectional_effect
    } else if (scenario == "dense_unidirectional") {
        abundance_effect[dense_set] <-
            config$dense_unidirectional_effect
    } else if (scenario == "structural_only") {
        structural_effect[structural_set] <-
            config$structural_log_odds_effect * structural_direction
    } else if (scenario == "mixed_structural_abundance") {
        abundance_effect[balanced_set] <-
            config$balanced_abundance_effect * balanced_direction
        structural_effect[structural_set] <-
            config$structural_log_odds_effect * structural_direction
    }

    list(
        abundance_effect = abundance_effect,
        structural_effect = structural_effect,
        baseline_log_offset = baseline_log_offset,
        structural_log_odds_offset = structural_log_odds_offset,
        balanced_set = balanced_set,
        rare_set = rare_set,
        sparse_set = sparse_set,
        dense_set = dense_set,
        structural_set = structural_set
    )
}

oracle_taxon_summary <- function(relative_abundance, counts, structural_absent,
                                 group, z, direct_effect) {
    p <- ncol(relative_abundance)
    rows <- vector("list", p)
    for (j in seq_len(p)) {
        present <- !structural_absent[, j]
        detected <- counts[, j] > 0

        latent_coefficient <- NA_real_
        if (sum(present) >= 8L &&
            length(unique(group[present])) == 2L) {
            latent_fit <- tryCatch(
                lm(
                    log(relative_abundance[present, j]) ~
                        group[present] + z[present]
                ),
                error = function(e) NULL
            )
            if (!is.null(latent_fit)) {
                latent_coefficient <- unname(coef(latent_fit)[2L])
            }
        }

        detected_coefficient <- NA_real_
        if (sum(detected) >= 8L &&
            length(unique(group[detected])) == 2L) {
            detected_fit <- tryCatch(
                lm(
                    log(counts[detected, j] /
                            rowSums(counts)[detected]) ~
                        group[detected] + z[detected]
                ),
                error = function(e) NULL
            )
            if (!is.null(detected_fit)) {
                detected_coefficient <- unname(coef(detected_fit)[2L])
            }
        }

        rows[[j]] <- data.frame(
            oracle_latent_log_relative_effect = latent_coefficient,
            oracle_detected_log_relative_effect = detected_coefficient,
            present_nondetection_reference = if (any(present & group == 0)) {
                mean(counts[present & group == 0, j] == 0)
            } else {
                NA_real_
            },
            present_nondetection_comparison = if (any(present & group == 1)) {
                mean(counts[present & group == 1, j] == 0)
            } else {
                NA_real_
            },
            direct_log_absolute_effect = direct_effect[j],
            stringsAsFactors = FALSE
        )
    }
    dplyr::bind_rows(rows)
}

simulate_scenario <- function(base, scenario, rep_id, dgp, config) {
    n <- length(base$group)
    p <- config$n_taxa
    signal <- scenario_signal_vectors(base, scenario, config)

    scenario_depth <- base$depth
    if (scenario == "depth_imbalanced_null") {
        comparison <- base$group == 1
        scenario_depth[comparison] <- as.integer(clamp(
            round(scenario_depth[comparison] *
                      config$depth_imbalance_multiplier),
            config$depth_min,
            config$depth_max
        ))
    }

    lp_rho <- matrix(
        base$rho_intercept + signal$structural_log_odds_offset,
        nrow = n, ncol = p, byrow = TRUE
    ) +
        outer(base$z, base$rho_z_effect) +
        outer(base$group, signal$structural_effect)
    rho <- plogis(lp_rho)
    structural_absent <- base$structural_uniform < rho

    scenario_abundance_intercept <-
        base$abundance_intercept + signal$baseline_log_offset
    log_absolute <- matrix(
        scenario_abundance_intercept, nrow = n, ncol = p, byrow = TRUE
    ) +
        outer(base$z, base$abundance_z_effect) +
        outer(base$sample_factor, base$factor_loading) +
        outer(base$group, signal$abundance_effect) +
        matrix(
            base$abundance_error, nrow = n, ncol = p
        ) * matrix(
            base$abundance_sd, nrow = n, ncol = p, byrow = TRUE
        )

    absolute_abundance <- exp(log_absolute)
    absolute_abundance[structural_absent] <- 0

    zero_rows <- which(rowSums(absolute_abundance) <= 0)
    if (length(zero_rows)) {
        anchor <- which.max(scenario_abundance_intercept)
        absolute_abundance[zero_rows, anchor] <-
            exp(scenario_abundance_intercept[anchor])
        structural_absent[zero_rows, anchor] <- FALSE
    }

    relative_abundance <- absolute_abundance / rowSums(absolute_abundance)

    set.seed(
        config$base_seed + 1000000L + 10000L * rep_id +
            100L * match(scenario, SCENARIOS$scenario) +
            if (identical(dgp, "heavy_tail")) 50L else 0L
    )
    count_by_sample <- t(vapply(seq_len(n), function(i) {
        as.numeric(rmultinom(
            1L, size = scenario_depth[i], prob = relative_abundance[i, ]
        )[, 1L])
    }, numeric(p)))

    rownames(count_by_sample) <- base$samples
    colnames(count_by_sample) <- base$taxa

    retained <- colSums(count_by_sample > 0) >= 3L
    oracle <- oracle_taxon_summary(
        relative_abundance = relative_abundance,
        counts = count_by_sample,
        structural_absent = structural_absent,
        group = base$group,
        z = base$z,
        direct_effect = signal$abundance_effect
    )

    truth <- data.frame(
        target = base$taxa,
        retained = retained,
        abundance_alt = signal$abundance_effect != 0,
        structural_alt = signal$structural_effect != 0,
        abundance_effect = signal$abundance_effect,
        structural_effect = signal$structural_effect,
        baseline_relative_abundance =
            exp(scenario_abundance_intercept) /
            sum(exp(scenario_abundance_intercept)),
        n_positive_reference =
            colSums(count_by_sample[base$group == 0, , drop = FALSE] > 0),
        n_positive_comparison =
            colSums(count_by_sample[base$group == 1, , drop = FALSE] > 0),
        stringsAsFactors = FALSE
    )
    truth <- cbind(truth, oracle)

    list(
        counts = count_by_sample,
        depth = scenario_depth,
        group = base$group,
        z = matrix(base$z, ncol = 1L),
        structural_absent = structural_absent,
        relative_abundance = relative_abundance,
        truth = truth
    )
}

