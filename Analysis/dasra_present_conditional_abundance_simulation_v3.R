extract_maaslin3_abundance <- function(fit, target_names) {
    abundance <- fit$fit_data_abundance
    results <- if (is.data.frame(abundance)) {
        abundance
    } else {
        abundance$results
    }

    if (is.null(results) || !is.data.frame(results)) {
        return(empty_method_rows(
            target_names,
            "MaAsLin 3 abundance",
            "abundance_results_unavailable"
        ))
    }

    rows <- vector("list", length(target_names))
    for (j in seq_along(target_names)) {
        target <- target_names[j]
        candidates <- results[results$feature == target, , drop = FALSE]
        if ("model" %in% names(candidates)) {
            # MaAsLin 3 labels abundance-model rows as "linear" and
            # prevalence-model rows as "logistic".  Accept "abundance" as
            # well for compatibility with versions that use component labels.
            model_label <- tolower(trimws(as.character(candidates$model)))
            candidates <- candidates[
                model_label %in% c("linear", "abundance"),
                , drop = FALSE
            ]
        }
        if ("metadata" %in% names(candidates)) {
            candidates <- candidates[
                as.character(candidates$metadata) == "group",
                , drop = FALSE
            ]
        }
        if (nrow(candidates) > 1L && "value" %in% names(candidates)) {
            preferred <- as.character(candidates$value) == "case"
            if (any(preferred, na.rm = TRUE)) {
                candidates <- candidates[which(preferred)[1L], , drop = FALSE]
            }
        }
        if (nrow(candidates) > 1L && "name" %in% names(candidates)) {
            preferred <- gsub(" ", "", as.character(candidates$name)) ==
                "groupcase"
            if (any(preferred, na.rm = TRUE)) {
                candidates <- candidates[which(preferred)[1L], , drop = FALSE]
            }
        }

        if (!nrow(candidates)) {
            rows[[j]] <- empty_method_rows(
                target, "MaAsLin 3 abundance",
                "target_abundance_row_unavailable"
            )
            next
        }

        candidate <- candidates[1L, , drop = FALSE]
        p_value <- suppressWarnings(as.numeric(candidate$pval_individual)[1L])
        coefficient <- if ("coef" %in% names(candidate)) {
            suppressWarnings(as.numeric(candidate$coef)[1L])
        } else {
            NA_real_
        }
        standard_error <- if ("stderr" %in% names(candidate)) {
            suppressWarnings(as.numeric(candidate$stderr)[1L])
        } else {
            NA_real_
        }
        error_text <- if ("error" %in% names(candidate)) {
            as.character(candidate$error)[1L]
        } else {
            NA_character_
        }
        if (is.na(error_text) || identical(error_text, "NA") ||
            !nzchar(trimws(error_text))) {
            error_text <- NA_character_
        }

        available <- is.finite(p_value) && p_value >= 0 && p_value <= 1
        rows[[j]] <- data.frame(
            target = target,
            method = "MaAsLin 3 abundance",
            p_value = if (available) p_value else NA_real_,
            estimate = coefficient,
            standard_error = standard_error,
            available = available,
            status = if (available) {
                "ok"
            } else if (!is.na(error_text)) {
                error_text
            } else {
                "nonfinite_p_value"
            },
            stringsAsFactors = FALSE
        )
    }
    dplyr::bind_rows(rows)
}

run_maaslin3_abundance <- function(sim, config, rep_id, scenario_name) {
    target_names <- sim$truth$target
    if (!any(sim$truth$retained)) {
        return(empty_method_rows(
            target_names,
            "MaAsLin 3 abundance",
            "no_taxa_in_common_family"
        ))
    }

    output_dir <- tempfile(sprintf(
        "maaslin3_abundance_%04d_%s_", rep_id, scenario_name
    ))
    on.exit({
        try(maaslin3::maaslin_log_reset(), silent = TRUE)
        unlink(output_dir, recursive = TRUE, force = TRUE)
    }, add = TRUE)

    metadata <- data.frame(
        group = factor(
            ifelse(sim$group == 0, "control", "case"),
            levels = c("control", "case")
        ),
        z = sim$z[, 1L],
        log_depth = log(sim$depth),
        row.names = rownames(sim$counts)
    )

    arguments <- list(
        input_data = as.data.frame(
            sim$counts[, sim$truth$retained, drop = FALSE]
        ),
        input_metadata = metadata,
        output = output_dir,
        formula = "~ group + z + log_depth",
        min_abundance = 0,
        min_prevalence = 0,
        max_prevalence = 1.01,
        zero_threshold = 0,
        min_variance = 0,
        normalization = "TSS",
        transform = "LOG",
        correction = "BH",
        standardize = TRUE,
        median_comparison_abundance =
            isTRUE(config$maaslin3_median_comparison),
        median_comparison_prevalence = FALSE,
        warn_prevalence = FALSE,
        augment = TRUE,
        plot_summary_plot = FALSE,
        plot_associations = FALSE,
        max_pngs = 1,
        cores = 1,
        save_models = FALSE,
        save_plots_rds = FALSE,
        verbosity = "ERROR"
    )
    available_arguments <- names(formals(maaslin3::maaslin3))
    if ("evaluate_only" %in% available_arguments) {
        arguments$evaluate_only <- "abundance"
    }
    if ("subtract_median" %in% available_arguments) {
        arguments$subtract_median <- FALSE
    }
    arguments <- arguments[names(arguments) %in% available_arguments]

    warning_text <- character()
    set.seed(
        config$base_seed + rep_id * 10007L +
            match(scenario_name, SCENARIOS$scenario)
    )
    try(maaslin3::maaslin_log_reset(), silent = TRUE)
    fit <- tryCatch(
        {
            invisible(capture.output(
                fit_value <- withCallingHandlers(
                    suppressMessages(do.call(maaslin3::maaslin3, arguments)),
                    warning = function(w) {
                        warning_text <<- c(warning_text, conditionMessage(w))
                        invokeRestart("muffleWarning")
                    }
                )
            ))
            fit_value
        },
        error = function(e) e
    )

    if (inherits(fit, "error")) {
        return(empty_method_rows(
            target_names,
            "MaAsLin 3 abundance",
            paste0("error: ", conditionMessage(fit))
        ))
    }

    output <- extract_maaslin3_abundance(fit, target_names)
    global_warning <- collapse_conditions(warning_text)
    if (!is.na(global_warning)) output$warning <- global_warning
    output
}

