apply_common_multiplicity <- function(method_results, truth, alpha) {
    merged <- dplyr::left_join(method_results, truth, by = "target")
    merged$p_for_family <- ifelse(
        merged$retained & merged$available & is.finite(merged$p_value),
        merged$p_value,
        ifelse(merged$retained, 1, NA_real_)
    )
    merged$q_bh <- NA_real_

    # Each method defines one multiplicity family over the same retained taxa.
    # P-values from different methods are never pooled in the same BH adjustment.
    for (method_name in unique(merged$method)) {
        family <- which(
            merged$method == method_name &
                merged$retained &
                is.finite(merged$p_for_family)
        )
        if (length(family)) {
            merged$q_bh[family] <- p.adjust(
                merged$p_for_family[family], method = "BH"
            )
        }
    }

    merged$reject_raw <- merged$retained &
        is.finite(merged$p_for_family) &
        merged$p_for_family <= alpha
    merged$reject_bh <- merged$retained &
        is.finite(merged$q_bh) &
        merged$q_bh <= alpha
    merged
}

method_metrics <- function(result, rep_id, dgp, scenario, alpha) {
    methods <- unique(result$method)
    rows <- vector("list", length(methods))

    for (m in seq_along(methods)) {
        method <- methods[m]
        data <- result[result$method == method & result$retained, , drop = FALSE]
        alt <- data$abundance_alt
        null <- !alt
        rejected <- data$reject_bh
        n_rejected <- sum(rejected)
        false <- sum(rejected & null)
        true <- sum(rejected & alt)

        rows[[m]] <- data.frame(
            replicate = rep_id,
            dgp = dgp,
            scenario = scenario,
            method = method,
            n_family = nrow(data),
            n_alt = sum(alt),
            n_available = sum(data$available),
            n_rejected = n_rejected,
            n_false = false,
            n_true = true,
            fdp = if (n_rejected > 0L) false / n_rejected else 0,
            any_false = as.integer(false > 0L),
            power = if (sum(alt) > 0L) true / sum(alt) else NA_real_,
            raw_type1 = if (sum(null) > 0L) {
                mean(data$reject_raw[null])
            } else {
                NA_real_
            },
            conditional_raw_type1 = if (any(null & data$available)) {
                mean(data$p_value[null & data$available] <= alpha)
            } else {
                NA_real_
            },
            availability = if (nrow(data) > 0L) {
                mean(data$available)
            } else {
                NA_real_
            },
            stringsAsFactors = FALSE
        )
    }
    dplyr::bind_rows(rows)
}

analyze_scenario <- function(sim, config, rep_id, dgp, scenario) {
    proposed <- run_proposed_method(sim, config)
    zinq <- run_zinq_abundance(sim, config, rep_id)
    maaslin3 <- run_maaslin3_abundance(
        sim, config, rep_id, scenario
    )

    all_results <- dplyr::bind_rows(proposed, zinq, maaslin3)
    all_results <- apply_common_multiplicity(
        all_results, sim$truth, config$alpha
    )
    all_results$replicate <- rep_id
    all_results$dgp <- dgp
    all_results$scenario <- scenario

    list(
        raw = all_results,
        metrics = method_metrics(
            all_results, rep_id, dgp, scenario, config$alpha
        ),
        truth = transform(
            sim$truth,
            replicate = rep_id,
            dgp = dgp,
            scenario = scenario
        )
    )
}

run_replicate <- function(rep_id, config, run_signature) {
    checkpoint_file <- file.path(
        checkpoint_dir, sprintf("replicate_%04d.rds", rep_id)
    )
    if (isTRUE(config$resume) && file.exists(checkpoint_file)) {
        saved <- tryCatch(readRDS(checkpoint_file), error = function(e) NULL)
        if (!is.null(saved) &&
            identical(saved$run_signature, run_signature) &&
            isTRUE(saved$success)) {
            return(saved)
        }
    }

    result <- tryCatch({
        raw_list <- list()
        metric_list <- list()
        truth_list <- list()
        index <- 0L

        for (dgp in DGP_VARIANTS) {
            base <- make_base_replication(rep_id, dgp, config)
            for (scenario in SCENARIOS$scenario) {
                sim <- simulate_scenario(
                    base, scenario, rep_id, dgp, config
                )
                analyzed <- analyze_scenario(
                    sim, config, rep_id, dgp, scenario
                )
                index <- index + 1L
                raw_list[[index]] <- analyzed$raw
                metric_list[[index]] <- analyzed$metrics
                truth_list[[index]] <- analyzed$truth
            }
        }

        list(
            success = TRUE,
            replicate = rep_id,
            run_signature = run_signature,
            raw = dplyr::bind_rows(raw_list),
            metrics = dplyr::bind_rows(metric_list),
            truth = dplyr::bind_rows(truth_list),
            error = NA_character_
        )
    }, error = function(e) {
        list(
            success = FALSE,
            replicate = rep_id,
            run_signature = run_signature,
            raw = NULL,
            metrics = NULL,
            truth = NULL,
            error = conditionMessage(e)
        )
    })

    temporary <- paste0(
        checkpoint_file, ".tmp_", Sys.getpid(), "_",
        sample.int(1e8, 1L)
    )
    saveRDS(result, temporary)
    if (!file.rename(temporary, checkpoint_file)) {
        unlink(temporary)
        stop("Could not write checkpoint ", checkpoint_file, ".", call. = FALSE)
    }
    result
}

