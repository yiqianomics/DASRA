numeric_gradient <- function(par, fn, lower = rep(-Inf, length(par)),
                             upper = rep(Inf, length(par))) {
    par <- as.numeric(par)
    gradient <- numeric(length(par))
    f0 <- fn(par)
    for (k in seq_along(par)) {
        step <- 1e-4 * (1 + abs(par[k]))
        left_ok <- par[k] - step > lower[k]
        right_ok <- par[k] + step < upper[k]
        if (left_ok && right_ok) {
            left <- right <- par
            left[k] <- par[k] - step
            right[k] <- par[k] + step
            gradient[k] <- (fn(right) - fn(left)) / (2 * step)
        } else if (right_ok) {
            right <- par
            right[k] <- par[k] + step
            gradient[k] <- (fn(right) - f0) / step
        } else if (left_ok) {
            left <- par
            left[k] <- par[k] - step
            gradient[k] <- (f0 - fn(left)) / step
        } else {
            gradient[k] <- NA_real_
        }
    }
    gradient
}

numeric_jacobian <- function(par, fn, lower = rep(-Inf, length(par)),
                             upper = rep(Inf, length(par))) {
    par <- as.numeric(par)
    f0 <- as.numeric(fn(par))
    jacobian <- matrix(NA_real_, nrow = length(f0), ncol = length(par))
    for (k in seq_along(par)) {
        step <- 1e-4 * (1 + abs(par[k]))
        left_ok <- par[k] - step > lower[k]
        right_ok <- par[k] + step < upper[k]
        if (left_ok && right_ok) {
            left <- right <- par
            left[k] <- par[k] - step
            right[k] <- par[k] + step
            jacobian[, k] <- (fn(right) - fn(left)) / (2 * step)
        } else if (right_ok) {
            right <- par
            right[k] <- par[k] + step
            jacobian[, k] <- (fn(right) - f0) / step
        } else if (left_ok) {
            left <- par
            left[k] <- par[k] - step
            jacobian[, k] <- (f0 - fn(left)) / step
        }
    }
    jacobian
}

matrix_condition_number <- function(x) {
    singular_values <- tryCatch(
        svd(x, nu = 0, nv = 0)$d,
        error = function(e) numeric()
    )
    if (!length(singular_values) || any(!is.finite(singular_values)) ||
        min(singular_values) <= 0) {
        return(Inf)
    }
    max(singular_values) / min(singular_values)
}

