cauchy_combine_pvalues <- function(p_value, weight = NULL) {
    p_value <- as.numeric(p_value)
    if (!length(p_value) || any(!is.finite(p_value)) ||
        any(p_value < 0) || any(p_value > 1)) {
        return(NA_real_)
    }
    p_value <- clamp(p_value, 1e-15, 1 - 1e-15)
    if (is.null(weight)) weight <- rep(1 / length(p_value), length(p_value))
    weight <- as.numeric(weight)
    weight <- weight / sum(weight)
    statistic <- sum(weight * tan((0.5 - p_value) * pi))
    clamp(1 - pcauchy(statistic), 0, 1)
}

run_zinq_abundance <- function(sim, config, rep_id) {
    p <- ncol(sim$counts)
    rows <- vector("list", p)
    relative_abundance <- sim$counts / sim$depth
    tau_weight <- ifelse(
        config$zinq_taus <= 0.5,
        config$zinq_taus,
        1 - config$zinq_taus
    )
    tau_weight <- tau_weight / sum(tau_weight)

    for (j in seq_len(p)) {
        if (!sim$truth$retained[j]) {
            rows[[j]] <- data.frame(
                target = sim$truth$target[j],
                method = "ZINQ quantile abundance",
                p_value = NA_real_,
                estimate = NA_real_,
                standard_error = NA_real_,
                available = FALSE,
                status = "not_in_common_family",
                stringsAsFactors = FALSE
            )
            next
        }

        dat <- data.frame(
            Y = relative_abundance[, j],
            group = sim$group,
            z = sim$z[, 1L],
            log_depth = scale(log(sim$depth))[, 1L]
        )
        warning_text <- character()
        fit <- tryCatch(
            withCallingHandlers(
                ZINQ::ZINQ_tests(
                    formula.logistic = Y ~ group + z + log_depth,
                    formula.quantile = Y ~ group + z + log_depth,
                    C = "group",
                    y_CorD = "C",
                    data = dat,
                    taus = config$zinq_taus,
                    seed = config$base_seed + rep_id * 1009L + j
                ),
                warning = function(w) {
                    warning_text <<- c(warning_text, conditionMessage(w))
                    invokeRestart("muffleWarning")
                }
            ),
            error = function(e) e
        )

        p_value <- NA_real_
        status <- "official_function_failed"
        if (!inherits(fit, "error")) {
            quantile_p <- as.numeric(fit$pvalue.quantile)
            if (length(quantile_p) == length(config$zinq_taus) &&
                all(is.finite(quantile_p)) &&
                all(quantile_p >= 0) && all(quantile_p <= 1)) {
                p_value <- cauchy_combine_pvalues(quantile_p, tau_weight)
                status <- if (is.finite(p_value)) "ok" else "combination_failed"
            }
        } else {
            status <- paste0("error: ", conditionMessage(fit))
        }

        rows[[j]] <- data.frame(
            target = sim$truth$target[j],
            method = "ZINQ quantile abundance",
            p_value = p_value,
            estimate = NA_real_,
            standard_error = NA_real_,
            available = is.finite(p_value),
            status = status,
            warning = collapse_conditions(warning_text),
            stringsAsFactors = FALSE
        )
    }
    dplyr::bind_rows(rows)
}

