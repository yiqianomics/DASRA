clamp <- function(x, lower, upper) {
    pmin(pmax(x, lower), upper)
}

softplus <- function(x) {
    pmax(x, 0) + log1p(exp(-abs(x)))
}

log_plogis <- function(x) {
    -softplus(-x)
}

row_log_sum_exp <- function(x) {
    x <- as.matrix(x)
    maximum <- apply(x, 1L, max)
    output <- maximum + log(rowSums(exp(x - maximum)))
    bad <- !is.finite(maximum)
    output[bad] <- maximum[bad]
    output
}

log1mexp <- function(log_x) {
    log_x <- as.numeric(log_x)
    if (any(log_x > 1e-12, na.rm = TRUE)) {
        stop("log1mexp requires log_x <= 0.", call. = FALSE)
    }
    log_x <- pmin(log_x, 0)
    cutoff <- -log(2)
    output <- numeric(length(log_x))
    near_zero <- log_x > cutoff
    output[near_zero] <- log(-expm1(log_x[near_zero]))
    output[!near_zero] <- log1p(-exp(log_x[!near_zero]))
    output
}

safe_mean <- function(x) {
    if (!length(x) || all(is.na(x))) return(NA_real_)
    mean(x, na.rm = TRUE)
}

