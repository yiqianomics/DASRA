fit_proposed_taxon <- function(y, N, group, z,
                               gh_fit = GH_FIT,
                               gh_effect = GH_EFFECT,
                               config = CONFIG) {
    y <- as.numeric(y)
    N <- as.numeric(N)
    group <- as.numeric(group)
    z <- as.matrix(z)
    n <- length(y)

    if (length(N) != n || length(group) != n || nrow(z) != n ||
        any(!is.finite(y)) || any(!is.finite(N)) ||
        any(y < 0) || any(N <= 0) || any(y > N)) {
        return(empty_proposed_fit("invalid_input"))
    }

    design <- make_design_matrices(group, z)
    positive <- y > 0
    if (sum(positive) < 3L) {
        return(empty_proposed_fit("fewer_than_three_positive_counts"))
    }
    if (length(unique(group[positive])) < 2L) {
        return(empty_proposed_fit("positive_counts_in_one_group_only"))
    }
    if (qr(design$X_full)$rank < ncol(design$X_full) ||
        qr(design$X_rho)$rank < ncol(design$X_rho) ||
        qr(design$X_full[positive, , drop = FALSE])$rank <
            ncol(design$X_full)) {
        return(empty_proposed_fit("rank_deficient_design"))
    }

    layout <- proposed_parameter_layout(design$X_b, design$X_rho)
    bounds <- proposed_parameter_bounds(layout)
    data <- list(
        y = y,
        N = N,
        group = group,
        z = z,
        X_b = design$X_b,
        X_rho = design$X_rho,
        X_full = design$X_full,
        layout = layout
    )

    mark_fit <- fit_positive_mark_initial(data, gh_fit)
    if (is.null(mark_fit)) {
        return(empty_proposed_fit("positive_mark_initialization_failed"))
    }

    full_coefficient <- mark_fit$par[seq_len(ncol(design$X_full))]
    b_start <- c(full_coefficient[1L], full_coefficient[-c(1L, 2L)])
    if (ncol(design$X_full) == 2L) b_start <- full_coefficient[1L]
    zeta_start <- full_coefficient[2L]
    omega_start <- mark_fit$par[ncol(design$X_full) + 1L]

    detection_fit <- fit_detection_initial(
        data = data,
        b = b_start,
        omega = omega_start,
        zeta = zeta_start,
        gh = gh_fit
    )
    if (is.null(detection_fit)) {
        return(empty_proposed_fit("detection_initialization_failed"))
    }

    theta_start <- numeric(layout$dimension)
    theta_start[layout$b] <- b_start
    theta_start[layout$omega] <- omega_start
    theta_start[layout$a] <- detection_fit$par
    theta_start[layout$zeta] <- zeta_start
    theta_start <- clamp(theta_start, bounds$lower, bounds$upper)

    initial_state <- tryCatch(
        proposed_state(theta_start, data, gh_fit, return_psi = TRUE),
        error = function(e) NULL
    )
    if (is.null(initial_state)) {
        return(empty_proposed_fit("initial_estimating_equations_failed"))
    }
    equation_scale <- sqrt(colMeans(initial_state$psi^2))
    equation_scale[!is.finite(equation_scale) | equation_scale < 1e-3] <- 1

    equation_mean <- function(theta) {
        state <- tryCatch(
            proposed_state(theta, data, gh_fit, return_psi = TRUE),
            error = function(e) NULL
        )
        if (is.null(state)) {
            return(rep(1e3, layout$dimension))
        }
        colMeans(state$psi)
    }
    equation_scaled <- function(theta) {
        equation_mean(theta) / equation_scale
    }

    candidates <- list(theta_start)

    root_1 <- tryCatch(
        nleqslv::nleqslv(
            theta_start,
            equation_scaled,
            method = "Broyden",
            global = "dbldog",
            control = list(
                ftol = 1e-9,
                xtol = 1e-9,
                maxit = 150L,
                allowSingular = FALSE
            )
        ),
        error = function(e) NULL
    )
    if (!is.null(root_1) && all(is.finite(root_1$x))) {
        candidates[[length(candidates) + 1L]] <- root_1$x
    }

    best_before_optim <- candidates[[which.min(vapply(candidates, function(x) {
        value <- equation_scaled(x)
        if (any(!is.finite(value))) Inf else sum(value^2)
    }, numeric(1)))]]
    best_before_optim <- clamp(
        best_before_optim, bounds$lower, bounds$upper
    )

    score_objective <- function(theta) {
        value <- equation_scaled(theta)
        if (any(!is.finite(value))) return(1e12)
        sum(value^2) / 2
    }
    squared_fit <- tryCatch(
        optim(
            best_before_optim,
            score_objective,
            method = "L-BFGS-B",
            lower = bounds$lower,
            upper = bounds$upper,
            control = list(maxit = 500L, factr = 1e7)
        ),
        error = function(e) NULL
    )
    if (!is.null(squared_fit) && is.finite(squared_fit$value) &&
        all(is.finite(squared_fit$par))) {
        candidates[[length(candidates) + 1L]] <- squared_fit$par
        root_2 <- tryCatch(
            nleqslv::nleqslv(
                squared_fit$par,
                equation_scaled,
                method = "Newton",
                global = "dbldog",
                control = list(
                    ftol = 1e-10,
                    xtol = 1e-10,
                    maxit = 100L,
                    allowSingular = FALSE
                )
            ),
            error = function(e) NULL
        )
        if (!is.null(root_2) && all(is.finite(root_2$x))) {
            candidates[[length(candidates) + 1L]] <- root_2$x
        }
    }

    candidate_metric <- vapply(candidates, function(theta) {
        if (any(theta < bounds$lower) || any(theta > bounds$upper)) return(Inf)
        value <- equation_mean(theta)
        if (any(!is.finite(value))) Inf else max(abs(value))
    }, numeric(1))
    if (!any(is.finite(candidate_metric))) {
        return(empty_proposed_fit("estimating_equation_solver_failed"))
    }

    theta_hat <- candidates[[which.min(candidate_metric)]]
    residue <- min(candidate_metric)
    if (!is.finite(residue) || residue > config$root_tolerance) {
        return(empty_proposed_fit("estimating_equation_residue"))
    }

    boundary_distance <- pmin(
        theta_hat - bounds$lower,
        bounds$upper - theta_hat
    )
    if (any(boundary_distance <= config$parameter_boundary_tolerance)) {
        return(empty_proposed_fit("parameter_on_boundary"))
    }

    fitted_state <- tryCatch(
        proposed_state(theta_hat, data, gh_fit, return_psi = TRUE),
        error = function(e) NULL
    )
    if (is.null(fitted_state) || any(!is.finite(fitted_state$psi))) {
        return(empty_proposed_fit("fitted_state_failed"))
    }

    jacobian_mean <- numeric_jacobian(
        theta_hat, equation_mean,
        lower = bounds$lower, upper = bounds$upper
    )
    condition <- matrix_condition_number(jacobian_mean)
    if (any(!is.finite(jacobian_mean)) ||
        !is.finite(condition) ||
        condition > config$jacobian_condition_limit) {
        return(empty_proposed_fit("singular_or_ill_conditioned_jacobian"))
    }

    delta_hat <- proposed_delta(theta_hat, data, gh_effect)
    delta_gradient <- numeric_gradient(
        theta_hat,
        function(theta) proposed_delta(theta, data, gh_effect),
        lower = bounds$lower,
        upper = bounds$upper
    )
    if (!is.finite(delta_hat) || any(!is.finite(delta_gradient))) {
        return(empty_proposed_fit("effect_gradient_failed"))
    }

    A_sum <- n * jacobian_mean
    parameter_contribution <- tryCatch(
        solve(A_sum, t(fitted_state$psi)),
        error = function(e) NULL
    )
    if (is.null(parameter_contribution) ||
        any(!is.finite(parameter_contribution))) {
        return(empty_proposed_fit("influence_solve_failed"))
    }

    phi <- -as.numeric(delta_gradient %*% parameter_contribution)
    raw_variance <- sum(phi^2)
    if (!is.finite(raw_variance) || raw_variance <= 0) {
        return(empty_proposed_fit("nonpositive_raw_variance"))
    }

    raw_se <- sqrt(raw_variance)
    raw_z <- delta_hat / raw_se
    raw_p <- 2 * pnorm(-abs(raw_z))

    list(
        available = TRUE,
        status = "ok",
        theta = theta_hat,
        raw_delta = delta_hat,
        raw_se = raw_se,
        raw_p = raw_p,
        phi = phi,
        score_residue = residue,
        jacobian_condition = condition,
        mean_presence_weight = mean(fitted_state$presence_weight),
        mean_zero_presence_weight = if (any(y == 0)) {
            mean(fitted_state$presence_weight[y == 0])
        } else {
            NA_real_
        }
    )
}


intercept_lts_pilot <- function(values) {
    values <- as.numeric(values)
    values <- values[is.finite(values)]
    m <- length(values)
    if (m < 3L) return(NA_real_)

    # A strict majority is retained. For an intercept-only least-trimmed-
    # squares problem in one dimension, an optimal subset is contiguous after
    # sorting. Ties are resolved by the first minimizing interval, making the
    # pilot deterministic.
    h <- floor(m / 2L) + 1L
    ordered <- sort(values)
    cumulative <- c(0, cumsum(ordered))
    cumulative_square <- c(0, cumsum(ordered^2))
    starts <- seq_len(m - h + 1L)
    sums <- cumulative[starts + h] - cumulative[starts]
    sums_square <- cumulative_square[starts + h] -
        cumulative_square[starts]
    sse <- sums_square - sums^2 / h
    best <- starts[which.min(sse)]
    mean(ordered[best:(best + h - 1L)])
}

compositionally_correct_proposed <- function(fits, truth, n_samples) {
    p <- length(fits)
    raw_delta <- vapply(fits, function(x) x$raw_delta, numeric(1))
    raw_se <- vapply(fits, function(x) x$raw_se, numeric(1))
    available <- vapply(fits, function(x) isTRUE(x$available), logical(1))

    output <- data.frame(
        target = truth$target,
        method = "DASRA proposed abundance",
        p_value = NA_real_,
        estimate = NA_real_,
        standard_error = NA_real_,
        available = FALSE,
        status = ifelse(available, "background_unavailable",
                        vapply(fits, `[[`, character(1), "status")),
        background_size = NA_integer_,
        background_pilot = NA_real_,
        background_estimate = NA_real_,
        background_reference_fraction = NA_real_,
        raw_estimate = raw_delta,
        raw_standard_error = raw_se,
        raw_p_value = vapply(fits, function(x) x$raw_p, numeric(1)),
        score_residue = vapply(fits, function(x) x$score_residue, numeric(1)),
        jacobian_condition = vapply(
            fits, function(x) x$jacobian_condition, numeric(1)
        ),
        mean_presence_weight = vapply(
            fits,
            function(x) x$mean_presence_weight %||% NA_real_,
            numeric(1)
        ),
        mean_zero_presence_weight = vapply(
            fits,
            function(x) x$mean_zero_presence_weight %||% NA_real_,
            numeric(1)
        ),
        stringsAsFactors = FALSE
    )

    eligible <- which(available & is.finite(raw_delta) & is.finite(raw_se) &
                          raw_se > 0)
    if (length(eligible) < 5L) {
        return(output)
    }

    phi_matrix <- matrix(NA_real_, nrow = n_samples, ncol = p)
    for (j in eligible) phi_matrix[, j] <- fits[[j]]$phi

    threshold <- sqrt(2 * log(max(n_samples * length(eligible), 3)))

    for (j in eligible) {
        others <- setdiff(eligible, j)
        if (length(others) < 3L) next

        pilot <- intercept_lts_pilot(raw_delta[others])
        if (!is.finite(pilot)) {
            output$status[j] <- "background_pilot_unavailable"
            next
        }
        studentized <- abs(raw_delta[others] - pilot) /
            pmax(raw_se[others], 1e-10)
        reference <- others[studentized <= threshold]

        if (length(reference) < 3L) {
            output$status[j] <- "fewer_than_three_reference_taxa"
            next
        }

        background <- mean(raw_delta[reference])
        phi_background <- rowMeans(phi_matrix[, reference, drop = FALSE])
        corrected_phi <- phi_matrix[, j] - phi_background
        variance <- sum(corrected_phi^2)

        if (!is.finite(variance) || variance <= 0) {
            output$status[j] <- "nonpositive_corrected_variance"
            next
        }

        corrected <- raw_delta[j] - background
        se <- sqrt(variance)
        p_value <- 2 * pnorm(-abs(corrected / se))

        output$p_value[j] <- p_value
        output$estimate[j] <- corrected
        output$standard_error[j] <- se
        output$available[j] <- is.finite(p_value)
        output$status[j] <- if (output$available[j]) "ok" else "nonfinite_p_value"
        output$background_size[j] <- length(reference)
        output$background_pilot[j] <- pilot
        output$background_estimate[j] <- background
        output$background_reference_fraction[j] <- mean(
            !truth$abundance_alt[reference]
        )
    }

    output
}

run_proposed_method <- function(sim, config) {
    p <- ncol(sim$counts)
    fits <- vector("list", p)
    for (j in seq_len(p)) {
        if (!sim$truth$retained[j]) {
            fits[[j]] <- empty_proposed_fit("not_in_common_family")
            next
        }
        fits[[j]] <- tryCatch(
            fit_proposed_taxon(
                y = sim$counts[, j],
                N = sim$depth,
                group = sim$group,
                z = sim$z,
                config = config
            ),
            error = function(e) empty_proposed_fit(
                paste0("error: ", conditionMessage(e))
            )
        )
    }
    compositionally_correct_proposed(
        fits = fits,
        truth = sim$truth,
        n_samples = nrow(sim$counts)
    )
}

