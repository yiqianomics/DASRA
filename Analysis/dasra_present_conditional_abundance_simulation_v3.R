summarize_metrics <- function(metrics) {
    metrics %>%
        group_by(dgp, scenario, method) %>%
        summarise(
            n_rep = n(),
            empirical_fdr = mean(fdp),
            mcse_fdr = safe_sd(fdp) / sqrt(n()),
            fdr_lower = pmax(0, empirical_fdr - 1.96 * mcse_fdr),
            fdr_upper = pmin(1, empirical_fdr + 1.96 * mcse_fdr),
            marginal_fwer = mean(any_false),
            mFDR = sum(n_false) / max(sum(n_rejected), 1),
            power = safe_mean(power),
            mcse_power = safe_sd(power) /
                sqrt(max(sum(is.finite(power)), 1)),
            power_lower = pmax(0, power - 1.96 * mcse_power),
            power_upper = pmin(1, power + 1.96 * mcse_power),
            raw_type1 = safe_mean(raw_type1),
            mcse_raw_type1 = safe_sd(raw_type1) /
                sqrt(max(sum(is.finite(raw_type1)), 1)),
            conditional_raw_type1 = safe_mean(conditional_raw_type1),
            availability = safe_mean(availability),
            mean_discoveries = mean(n_rejected),
            mean_false_discoveries = mean(n_false),
            .groups = "drop"
        )
}

