make_normal_gh_rule <- function(order) {
    rule <- statmod::gauss.quad(as.integer(order), kind = "hermite")
    node <- as.numeric(rule$nodes)
    raw_weight <- as.numeric(rule$weights)
    weight <- raw_weight / sum(raw_weight)
    list(
        order = as.integer(order),
        node = node,
        z = sqrt(2) * node,
        raw_weight = raw_weight,
        log_raw_weight = log(raw_weight),
        weight = weight,
        log_weight = log(weight)
    )
}

GH_FIT <- make_normal_gh_rule(CONFIG$quadrature_order)
GH_EFFECT <- make_normal_gh_rule(CONFIG$effect_quadrature_order)

latent_mode <- function(y, N, eta, sigma, maxit = 80L) {
    sigma2 <- sigma^2
    prior_precision <- 1 / sigma2
    pseudo_probability <- clamp(
        (y + 0.5) / (N + 1), 1e-12, 1 - 1e-12
    )
    x <- (
        qlogis(pseudo_probability) + prior_precision * eta
    ) / (1 + prior_precision)
    lower <- eta - sigma2 * (N - y)
    upper <- eta + sigma2 * y
    x <- clamp(x, lower, upper)

    for (iteration in seq_len(maxit)) {
        p <- plogis(x)
        score <- y - N * p - (x - eta) * prior_precision
        curvature <- N * p * (1 - p) + prior_precision
        positive_score <- score > 0
        lower[positive_score] <- x[positive_score]
        upper[!positive_score] <- x[!positive_score]

        newton <- x + score / curvature
        midpoint <- lower + 0.5 * (upper - lower)
        use_newton <- is.finite(newton) &
            newton > lower & newton < upper &
            abs(newton - x) <= 0.5 * (upper - lower)
        next_x <- ifelse(use_newton, newton, midpoint)
        converged <- abs(score / curvature) <= 1e-12 * (1 + abs(x)) |
            abs(upper - lower) <= 1e-12 * (1 + abs(x))
        next_x[converged] <- x[converged]
        x <- next_x
        if (all(converged)) break
    }

    p <- plogis(x)
    score <- y - N * p - (x - eta) * prior_precision
    curvature <- N * p * (1 - p) + prior_precision
    if (any(!is.finite(x)) || any(!is.finite(curvature)) ||
        any(curvature <= 0) ||
        any(abs(score / curvature) > 1e-8 * (1 + abs(x)))) {
        stop("Adaptive latent-mode solver failed.", call. = FALSE)
    }
    list(mode = x, curvature = curvature)
}

gh_binomial_marginal <- function(y, N, eta, sigma, gh, need_posterior = TRUE) {
    y <- as.numeric(y)
    N <- as.numeric(N)
    eta <- as.numeric(eta)
    n <- length(y)
    if (length(N) != n || length(eta) != n ||
        !is.finite(sigma) || sigma <= 0) {
        stop("Invalid inputs to gh_binomial_marginal.", call. = FALSE)
    }

    mode_information <- latent_mode(y, N, eta, sigma)
    mode <- mode_information$mode
    curvature <- mode_information$curvature
    q <- length(gh$node)
    scale <- sqrt(2 / curvature)

    x <- matrix(mode, nrow = n, ncol = q) +
        matrix(scale, nrow = n, ncol = q) *
        matrix(gh$node, nrow = n, ncol = q, byrow = TRUE)
    centered <- x - matrix(eta, nrow = n, ncol = q)

    log_kernel <- sweep(x, 1L, y, "*") -
        sweep(softplus(x), 1L, N, "*") -
        sweep(centered^2, 1L, rep(2 * sigma^2, n), "/") -
        log(sigma) - 0.5 * log(2 * pi)
    log_terms <- log_kernel +
        matrix(gh$node^2, nrow = n, ncol = q, byrow = TRUE) +
        matrix(
            gh$log_raw_weight, nrow = n, ncol = q, byrow = TRUE
        )
    log_normalizer <- row_log_sum_exp(log_terms)
    log_choose <- lgamma(N + 1) - lgamma(y + 1) - lgamma(N - y + 1)
    log_h <- log_choose + 0.5 * log(2 / curvature) + log_normalizer

    if (!isTRUE(need_posterior)) {
        return(list(log_h = log_h))
    }

    posterior_weight <- exp(log_terms - log_normalizer)
    posterior_m1 <- rowSums(posterior_weight * centered)
    posterior_m2 <- rowSums(posterior_weight * centered^2)

    list(
        log_h = log_h,
        posterior_weight = posterior_weight,
        score_eta = posterior_m1 / sigma^2,
        score_omega = posterior_m2 / sigma^2 - 1,
        posterior_m1 = posterior_m1,
        posterior_m2 = posterior_m2,
        posterior_mean_x = rowSums(posterior_weight * x),
        posterior_mean_log_q = rowSums(
            posterior_weight * (-softplus(-x))
        )
    )
}

normal_mean_log_relative <- function(location, sigma, gh = GH_EFFECT) {
    location <- as.numeric(location)
    x <- matrix(location, nrow = length(location), ncol = length(gh$z)) +
        sigma * matrix(
            gh$z, nrow = length(location), ncol = length(gh$z),
            byrow = TRUE
        )
    as.numeric((-softplus(-x)) %*% gh$weight)
}

