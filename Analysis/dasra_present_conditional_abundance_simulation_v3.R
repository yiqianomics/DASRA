make_design_matrices <- function(group, z) {
    group <- as.numeric(group)
    z <- as.matrix(z)
    if (!ncol(z)) {
        X_b <- matrix(1, nrow = length(group), ncol = 1L)
        X_rho <- cbind(Intercept = 1, Group = group)
        X_full <- cbind(Intercept = 1, Group = group)
    } else {
        X_b <- cbind(Intercept = 1, z)
        colnames(X_b) <- c("Intercept", paste0("z", seq_len(ncol(z))))
        X_rho <- cbind(Intercept = 1, Group = group, z)
        colnames(X_rho) <- c(
            "Intercept", "Group", paste0("z", seq_len(ncol(z)))
        )
        X_full <- X_rho
    }
    list(X_b = X_b, X_rho = X_rho, X_full = X_full)
}

proposed_parameter_layout <- function(X_b, X_rho) {
    nb <- ncol(X_b)
    na <- ncol(X_rho)
    list(
        nb = nb,
        na = na,
        b = seq_len(nb),
        omega = nb + 1L,
        a = nb + 1L + seq_len(na),
        zeta = nb + na + 2L,
        dimension = nb + na + 2L
    )
}

