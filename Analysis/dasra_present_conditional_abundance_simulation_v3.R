env_flag <- function(name, default = FALSE) {
    value <- tolower(trimws(Sys.getenv(
        name, if (isTRUE(default)) "true" else "false"
    )))
    if (value %in% c("1", "true", "t", "yes", "y")) return(TRUE)
    if (value %in% c("0", "false", "f", "no", "n")) return(FALSE)
    stop(name, " must be true or false.", call. = FALSE)
}

env_integer <- function(name, default, minimum = 1L) {
    value <- suppressWarnings(as.integer(Sys.getenv(name, as.character(default))))
    if (length(value) != 1L || !is.finite(value) || value < minimum) {
        stop(name, " must be an integer at least ", minimum, ".", call. = FALSE)
    }
    value
}

